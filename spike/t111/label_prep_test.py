    def test_commit_set_attempt_rejects_rebinding_tampering_and_symlink(self) -> None:
        commits = {
            system: f"{index + 1:040x}"
            for index, system in enumerate(prep.SYSTEMS)
        }
        base = "sha256:" + "a" * 64
        final = "sha256:" + "b" * 64
        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            with patch.object(prep, "SEALED_CLAIM_ROOT", root):
                claim = prep.locked_attempt_claim(
                    commits=commits,
                    base_input_binding=base,
                    input_binding=final,
                    committed_at="2026-07-13T12:00:30Z",
                    create=True,
                )
                self.assertEqual(claim["input_binding"], final)
                repeated = prep.locked_attempt_claim(
                    commits=commits,
                    base_input_binding=base,
                    input_binding=final,
                    committed_at="2026-07-13T12:00:30Z",
                    create=True,
                )
                self.assertEqual(repeated, claim)
                with self.assertRaisesRegex(prep.PrepError, "different final input"):
                    prep.locked_attempt_claim(
                        commits=commits,
                        base_input_binding=base,
                        input_binding="sha256:" + "e" * 64,
                        committed_at="2026-07-13T12:01:30Z",
                        create=True,
                    )
                with self.assertRaisesRegex(prep.PrepError, "different input lineage"):
                    prep.locked_attempt_claim(
                        commits=commits,
                        base_input_binding="sha256:" + "c" * 64,
                        input_binding=None,
                        committed_at=None,
                        create=False,
                    )
                path = next(root.glob(".t111-gate2-source-*.attempt.json"))
                path.write_text("{}\n", encoding="utf-8")
                with self.assertRaisesRegex(prep.PrepError, "invalid.*attempt"):
                    prep.locked_attempt_claim(
                        commits=commits,
                        base_input_binding=base,
                        input_binding=final,
                        committed_at=None,
                        create=False,
                    )

        with tempfile.TemporaryDirectory() as raw:
            root = Path(raw)
            lineage = prep.commit_set_lineage_binding(commits).removeprefix("sha256:")
            target = root / "target.json"
            target.write_text("{}\n", encoding="utf-8")
            (root / f".t111-gate2-source-{lineage}.attempt.json").symlink_to(target)
            with patch.object(prep, "SEALED_CLAIM_ROOT", root):
                with self.assertRaisesRegex(prep.PrepError, "missing persistent"):
                    prep.locked_attempt_claim(
                        commits=commits,
                        base_input_binding=base,
                        input_binding=final,
                        committed_at=None,
                        create=False,
                    )

