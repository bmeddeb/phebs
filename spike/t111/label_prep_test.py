    def test_seed_receipt_rejects_constants_and_wrong_input_binding(self) -> None:
        binding = "sha256:" + "a" * 64
        valid = self._seed_record(binding)
        self.assertEqual(
            prep.validate_seed_record(valid, expected_input_binding=binding), valid
        )
        with self.assertRaisesRegex(prep.PrepError, "different locked inputs"):
            prep.validate_seed_record(
                valid, expected_input_binding="sha256:" + "b" * 64
            )
        with self.assertRaisesRegex(prep.PrepError, "legacy, zero"):
            prep.validate_seed_record(
                {**valid, "seed_hex": f"{prep.LEGACY_DIAGNOSTIC_SEED:064x}"}
            )
        with self.assertRaisesRegex(prep.PrepError, "legacy, zero"):
            prep.validate_seed_record(
                {**valid, "seed_hex": binding.removeprefix("sha256:")}
            )
        with self.assertRaisesRegex(prep.PrepError, "plausible entropy"):
            prep.validate_seed_record(
                {**valid, "seed_hex": "0123456789abcdef" * 4}
            )
        with self.assertRaisesRegex(prep.PrepError, "independently auditable"):
            prep.validate_seed_record({**valid, "source": "os_csprng"})
        with self.assertRaisesRegex(prep.PrepError, "recorded after"):
            prep.validate_seed_record(
                {**valid, "recorded_at": valid["input_committed_at"]}
            )
        beacon = self._seed_record(binding, source="public_randomness_beacon")
        with self.assertRaisesRegex(prep.PrepError, "official NIST"):
            prep.validate_seed_record(
                {**beacon, "source_reference": "https://example.test/pulse/1"}
            )
        with self.assertRaisesRegex(prep.PrepError, "complete"):
            prep.validate_seed_record({**valid, "unexpected": True})
        with self.assertRaisesRegex(prep.PrepError, "persistent input commitment time"):
            prep.validate_seed_record(
                valid,
                expected_input_binding=binding,
                expected_input_committed_at="2026-07-13T11:59:00Z",
            )

