    def test_only_exact_declared_gitlink_is_excluded(self) -> None:
        commit = "1" * 40
        gitlink = "2" * 40
        tree = (
            f"100644 blob {'3' * 40}\tmain.go\0"
            f"160000 commit {gitlink}\tdocs/theme\0"
        ).encode()

        def fake_git(_root: Path, *arguments: str) -> bytes:
            if arguments[:2] == ("rev-parse", "--verify"):
                return (commit + "\n").encode()
            if arguments and arguments[0] == "status":
                return b""
            if arguments and arguments[0] == "ls-tree":
                return tree
            raise AssertionError(arguments)

        with tempfile.TemporaryDirectory() as raw, patch.object(prep, "git", fake_git):
            root = Path(raw)
            with self.assertRaisesRegex(prep.PrepError, "undeclared gitlink"):
                prep.pinned_tracked_files(root, commit)
            wrong = [{"path": "docs/theme", "object_id": "4" * 40, "reason": "docs"}]
            with self.assertRaisesRegex(prep.PrepError, "does not match"):
                prep.pinned_tracked_files(root, commit, wrong)
            exact = [{"path": "docs/theme", "object_id": gitlink, "reason": "docs"}]
            files, special = prep.pinned_tracked_files(root, commit, exact)
            self.assertEqual(files, ["main.go"])
            self.assertEqual(special, [{"kind": "gitlink", **exact[0]}])
            absent = [{"path": "docs/other", "object_id": gitlink, "reason": "docs"}]
            with self.assertRaisesRegex(prep.PrepError, "undeclared gitlink"):
                prep.pinned_tracked_files(root, commit, absent)

