func TestOracleFindsDirectConcreteAndEmbeddedCalls(t *testing.T) {
	root, commit := makeFixture(t, clientFixtureFiles("app/application.go", applicationSource))

	first, firstDiag := runFixture(t, root, commit)
	second, secondDiag := runFixture(t, root, commit)
	if !bytes.Equal(first, second) {
		t.Fatalf("output is not deterministic:\nfirst=%s\nsecond=%s", first, second)
	}
	if !bytes.Equal(firstDiag, secondDiag) {
		t.Fatalf("diagnostics are not deterministic:\nfirst=%s\nsecond=%s", firstDiag, secondDiag)
	}

	got := decodeRecords(t, first)
	if len(got) != 4 {
		t.Fatalf("got %d records, want 4: %#v", len(got), got)
	}
	wantMethods := []string{"Get", "Get", "Put", "Get"}
	wantStrata := []string{
		stratumGeneratedClient,
		stratumConcreteClient,
		stratumEmbeddedClient,
		stratumAmbiguousClient,
	}
	for i, item := range got {
		if item.Path != "app/application.go" || item.Method != wantMethods[i] || item.Stratum != wantStrata[i] {
			t.Errorf("record %d = %#v", i, item)
		}
	}
	if !(got[0].ByteOffset < got[1].ByteOffset && got[1].ByteOffset < got[2].ByteOffset) {
		t.Fatalf("records are not in deterministic coordinate order: %#v", got)
	}
	for _, excluded := range []string{"unrelated.Get", "cc.Invoke"} {
		method := strings.TrimPrefix(excluded[strings.Index(excluded, "."):], ".")
		offset := strings.Index(applicationSource, excluded)
		if excluded == "cc.Invoke" {
			offset = strings.Index(generatedClientSource, excluded)
		}
		if offset < 0 {
			t.Fatalf("fixture is missing %s", excluded)
		}
		for _, item := range got {
			if item.Method == method && item.ByteOffset == offset+strings.Index(excluded, ".")+1 {
				t.Errorf("excluded call was emitted: %s", excluded)
			}
		}
	}

	var diag diagnostics
	if err := json.Unmarshal(bytes.TrimSpace(firstDiag), &diag); err != nil {
		t.Fatalf("decode diagnostics: %v\n%s", err, firstDiag)
	}
	if diag.MatchedSites != 4 || diag.AmbiguousSites != 1 || diag.GeneratedClientInterfaces != 3 {
		t.Fatalf("unexpected diagnostics: %#v", diag)
	}
}

func TestExactNamedClientWinsOverSameShapedGeneratedInterface(t *testing.T) {
	root, commit := makeFixture(t, clientFixtureFiles(
		"app/application.go",
		`package app

import (
	"context"
	"example.com/fixture/pb"
)

func Call(client pb.FooClient, ctx context.Context, request *pb.Request) {
	client.Get(ctx, request)
}
`,
	))
	// Make BarClient structurally identical to FooClient. The statically named
	// FooClient receiver must still resolve directly rather than disappear as
	// an ambiguous structural match.
	path := filepath.Join(root, "pb", "client.pb.go")
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	content = bytes.ReplaceAll(
		content,
		[]byte("\tBarOnly(context.Context, *Request, ...grpc.CallOption) (*Response, error)\n"),
		[]byte("\tFooOnly(context.Context, *Request, ...grpc.CallOption) (*Response, error)\n"),
	)
	if err := os.WriteFile(path, content, 0o644); err != nil {
		t.Fatal(err)
	}
	runGit(t, root, "add", "pb/client.pb.go")
	runGit(t, root, "commit", "-q", "-m", "same-shaped clients")
	commit = strings.TrimSpace(runGit(t, root, "rev-parse", "HEAD"))

	out, diagBytes := runFixture(t, root, commit)
	records := decodeRecords(t, out)
	if len(records) != 1 || records[0].Stratum != stratumGeneratedClient {
		t.Fatalf("same-shaped direct client records = %#v", records)
	}
	var diag diagnostics
	if err := json.Unmarshal(bytes.TrimSpace(diagBytes), &diag); err != nil {
		t.Fatal(err)
	}
	if diag.AmbiguousSites != 0 {
		t.Fatalf("same-shaped direct client was reported ambiguous: %#v", diag)
	}
}

