func runFixture(t *testing.T, root, commit string) ([]byte, []byte) {
	t.Helper()
	var out, diag bytes.Buffer
	if err := execute(options{root: root, commit: commit}, &out, &diag); err != nil {
		t.Fatal(err)
	}
	return out.Bytes(), diag.Bytes()
}

func decodeRecords(t *testing.T, data []byte) []record {
	t.Helper()
	var result []record
	dec := json.NewDecoder(bytes.NewReader(data))
	for dec.More() {
		var item record
		if err := dec.Decode(&item); err != nil {
			t.Fatal(err)
		}
		result = append(result, item)
	}
	return result
}

func clientFixtureFiles(applicationPath, application string) map[string]string {
	return map[string]string{
		"go.mod":              fixtureGoMod,
		"grpc/go.mod":         "module google.golang.org/grpc\n\ngo 1.23\n",
		"grpc/call_option.go": fakeGRPCSource,
		"pb/client.pb.go":     generatedClientSource,
		applicationPath:       application,
	}
}

func makeFixture(t *testing.T, files map[string]string) (string, string) {
	t.Helper()
	root := t.TempDir()
	runGit(t, root, "init", "-q")
	runGit(t, root, "config", "user.email", "oracle@example.invalid")
	runGit(t, root, "config", "user.name", "Oracle Test")
	for rel, content := range files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	runGit(t, root, "add", ".")
	runGit(t, root, "commit", "-q", "-m", "fixture")
	commit := strings.TrimSpace(runGit(t, root, "rev-parse", "HEAD"))
	if len(commit) != 40 {
		t.Fatalf("unexpected commit %q", commit)
	}
	return root, commit
}

func runGit(t *testing.T, root string, args ...string) string {
	t.Helper()
	cmd := exec.Command("git", append([]string{"-C", root}, args...)...)
	b, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("git %s: %v: %s", strings.Join(args, " "), err, b)
	}
	return string(b)
}

func assertFileBytes(t *testing.T, path string, want []byte) {
	t.Helper()
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("%s = %q, want %q", path, got, want)
	}
}

func lineColumn(text string, offset int) (int, int) {
	line := strings.Count(text[:offset], "\n") + 1
	last := strings.LastIndex(text[:offset], "\n")
	return line, offset - last
}

