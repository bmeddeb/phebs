func TestT40R1DescriptorPresentGitBlobPairDiagnostic(t *testing.T) {
	if os.Getenv(t40r1DescriptorGitBlobEnv) != "1" {
		t.Skip("set " + t40r1DescriptorGitBlobEnv + "=1 to run the descriptor/Git-blob diagnostic")
	}
	if _, err := exec.LookPath("surreal"); err != nil {
		t.Skip("surreal binary is not installed")
	}
	witness, measurement := runT40R1DescriptorGitBlobDiagnostic(t)
	encoded, err := json.MarshalIndent(witness, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	t.Logf(
		"candidate_build=%s resolver_build=%s resolver_open=%s pair_execute_seal=%s candidate_disk=%d resolver_disk=%d caller_disk=%d repository_disk=%d",
		measurement.CandidateBuild, measurement.ResolverBuild,
		measurement.ResolverOpen, measurement.PairExecuteSeal,
		measurement.CandidateDisk, measurement.ResolverDisk,
		measurement.CallerDisk, measurement.RepositoryDisk,
	)
	raw, err := os.ReadFile("descriptor-present-git-blob-pair.json")
	if err != nil {
		t.Fatalf("retained descriptor/Git-blob witness unavailable: %v\n%s", err, encoded)
	}
	var retained t40r1DescriptorGitBlobWitness
	if err := json.Unmarshal(raw, &retained); err != nil || !reflect.DeepEqual(retained, witness) {
		t.Fatalf("retained descriptor/Git-blob witness differs: %v\n%s", err, encoded)
	}
	t.Log(string(encoded))
}

