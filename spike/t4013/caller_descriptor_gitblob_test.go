func runT40R1DescriptorGitBlobDiagnostic(
	t *testing.T,
) (t40r1DescriptorGitBlobWitness, t40r1DescriptorGitBlobMeasurement) {
	t.Helper()
	ctx, cancel := context.WithTimeout(t.Context(), 10*time.Minute)
	defer cancel()
	dataDir := t.TempDir()
	state, err := store.OpenLocal(ctx, dataDir)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = state.Close(context.Background()) })
	repositoryDir, commit, objects := t40r1DescriptorGitBlobRepository(t, ctx)

	extractors := []extract.Extractor{gocaller.NewGRPC(), protodecl.New()}
	policies, err := extract.CandidatePolicies(extractors)
	if err != nil {
		t.Fatal(err)
	}
	policySet, err := candidatejob.CompilePolicies(extractors)
	if err != nil {
		t.Fatal(err)
	}
	callerRegistry, err := callerexecute.NewRegistry(extractors)
	if err != nil {
		t.Fatal(err)
	}
	resolverRegistry, err := resolvermaterialize.NewRegistry(extractors)
	if err != nil {
		t.Fatal(err)
	}
	candidateRoot := candidatejob.CandidateRoot(dataDir)
	if err := os.MkdirAll(candidateRoot, 0o700); err != nil {
		t.Fatal(err)
	}
	measurement := t40r1DescriptorGitBlobMeasurement{}
	started := time.Now()
	manifest, err := candidate.Build(ctx, candidate.Request{
		RepoDir: repositoryDir, OutputDir: candidateRoot,
		Repository: t40r1DescriptorGitBlobRepo, Commit: commit,
		Policies: policies,
	})
	measurement.CandidateBuild = time.Since(started)
	if err != nil {
		t.Fatal(err)
	}
	if err := state.UpsertRepo(ctx, store.Repo{
		Name:     t40r1DescriptorGitBlobRepo,
		CloneURL: "https://github.com/phebs/t40r1-descriptor-git-blob.invalid.git",
	}); err != nil {
		t.Fatal(err)
	}
	if err := state.SetRepoIndexed(ctx, t40r1DescriptorGitBlobRepo, commit, time.Now().UTC()); err != nil {
		t.Fatal(err)
	}
	if err := state.PublishCandidateManifest(ctx, store.CandidateManifestPublication{
		Repository: t40r1DescriptorGitBlobRepo, HeadCommit: commit,
		PolicyDigest: manifest.PolicyDigest, ManifestDigest: manifest.Digest,
		GenerationDigest: manifest.GenerationDigest,
		ManifestPath:     candidate.ManifestName(t40r1DescriptorGitBlobRepo),
	}); err != nil {
		t.Fatal(err)
	}
	candidatePointer, err := state.GetCandidateManifestPublication(ctx, t40r1DescriptorGitBlobRepo)
	if err != nil {
		t.Fatal(err)
	}
	provider, err := candidatejob.NewProvider(dataDir, state, policySet)
	if err != nil {
		t.Fatal(err)
	}
	manifestView, err := provider.OpenCandidateManifest(ctx, extract.CandidateManifestRequest{
		Repository: t40r1DescriptorGitBlobRepo, Commit: commit,
		Domains: resolverRegistry.CandidateDomains(),
	})
	if err != nil {
		t.Fatal(err)
	}
	plan, err := provider.OpenCandidateCallerPlan(ctx, extract.CandidateManifestRequest{
		Repository: t40r1DescriptorGitBlobRepo, Commit: commit,
		Domains: callerRegistry.CandidateDomains(),
	})
	if err != nil {
		t.Fatal(err)
	}

	declarationRun, declarationGeneration := t40r1PublishDescriptorDeclaration(
		t, ctx, state, *candidatePointer, commit,
	)
	declarations := []resolvercatalog.DeclarationPublication{{
		Domain: "proto-contract", RunID: declarationRun.ID,
		GenerationDigest: declarationGeneration,
	}}
	resolverIdentity, err := resolvercatalog.NewIdentity(
		t40r1DescriptorGitBlobRepo, commit, "", candidatePointer.ManifestDigest,
		declarations, resolverRegistry.Packs(),
	)
	if err != nil {
		t.Fatal(err)
	}
	resolverRoot := filepath.Join(dataDir, "resolver-catalogs")
	if err := os.MkdirAll(resolverRoot, 0o700); err != nil {
		t.Fatal(err)
	}
	resolverBlobReads := 0
	resolverBlobBytes := int64(0)
	started = time.Now()
	preparedResolver, err := resolvermaterialize.Build(ctx, resolvermaterialize.BuildRequest{
		Root: resolverRoot, RepositoryDir: repositoryDir,
		Identity: resolverIdentity, Registry: resolverRegistry, Manifest: manifestView,
		Declarations: []resolvermaterialize.DeclarationInput{{
			Protocol: resolvermaterialize.ProtocolGRPC,
			Domain:   "proto-contract", RunID: declarationRun.ID,
			GenerationDigest: declarationGeneration,
		}},
		Assertions: state,
		ReadBlob: func(readCtx context.Context, directory, oid string, limit int64) ([]byte, error) {
			content, readErr := gitobj.ReadBlob(readCtx, directory, oid, limit)
			if readErr == nil {
				resolverBlobReads++
				resolverBlobBytes += int64(len(content))
			}
			return content, readErr
		},
	})
	measurement.ResolverBuild = time.Since(started)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = preparedResolver.Discard() })
	resolverState, err := preparedResolver.Publish(
		ctx, func(commitCtx context.Context, current resolvercatalog.State) error {
			return state.PublishResolverCatalog(commitCtx, t40r1CallerUpstreamResolverPointer(current))
		},
	)
	if err != nil {
		t.Fatal(err)
	}
	resolverPointer, err := state.GetResolverCatalogPublication(ctx, t40r1DescriptorGitBlobRepo)
	if err != nil {
		t.Fatal(err)
	}
	resolverCurrent, err := state.ResolverCatalogPublicationCurrent(ctx, *resolverPointer)
	if err != nil {
		t.Fatal(err)
	}
	started = time.Now()
	resolverPublication, resolverView, err := resolvermaterialize.OpenCallerResolver(
		ctx, resolverRoot, resolverState, resolvermaterialize.ProtocolGRPC,
	)
	measurement.ResolverOpen = time.Since(started)
	if err != nil {
		t.Fatal(err)
	}
	descriptors := resolverView.Descriptors()
	if len(descriptors) != 1 {
		t.Fatalf("descriptor-present resolver count = %d", len(descriptors))
	}
	descriptor := descriptors[0]
	generatedExact, err := resolverView.Resolver().GeneratedSource(
		t40r1DescriptorGeneratedPath, objects[t40r1DescriptorGeneratedPath],
	)
	if err != nil {
		t.Fatal(err)
	}

	repository, err := state.GetRepo(ctx, t40r1DescriptorGitBlobRepo)
	if err != nil {
		t.Fatal(err)
	}
	generation, err := callerexecute.GenerationIdentity(callerexecute.GenerationAuthority{
		Repository: repository, Candidate: candidatePointer, Resolver: resolverPointer,
	}, callerRegistry)
	if err != nil {
		t.Fatal(err)
	}
	pairs, _, err := callerexecute.ExpectedPairs(plan, generation, callerRegistry)
	if err != nil {
		t.Fatal(err)
	}
	selectedLeaf, selectedRecords := t40r1DescriptorSelectLeaf(t, ctx, plan)
	selectedPair := t40r1DescriptorSelectPair(t, pairs, selectedLeaf)
	callerRoot := filepath.Join(dataDir, "caller-leaves")
	stage, err := callerleaf.NewStage(callerRoot, generation, selectedPair.Identity)
	if err != nil {
		t.Fatal(err)
	}
	started = time.Now()
	if err := callerexecute.ExecutePair(ctx, callerexecute.ExecuteRequest{
		RepositoryDir: repositoryDir, Plan: plan, Pair: selectedPair,
		Protocol: "grpc", ResolverCatalogDigest: resolverState.ManifestDigest,
		Resolver: resolverView.Resolver(), Stage: stage,
	}); err != nil {
		t.Fatal(err)
	}
	preparedPair, err := stage.Seal()
	measurement.PairExecuteSeal = time.Since(started)
	if err != nil {
		t.Fatal(err)
	}
	receipt := preparedPair.Receipt()
	publication, err := preparedPair.Install(ctx)
	if err != nil {
		t.Fatal(err)
	}
	var records []callerleaf.Record
	if err := publication.ScanRecords(
		ctx, generation, selectedPair.Identity,
		func(_ callerleaf.RecordReference, record callerleaf.Record) error {
			records = append(records, record)
			return nil
		},
	); err != nil {
		t.Fatal(err)
	}
	if len(records) != 1 || records[0].Fact == nil {
		t.Fatalf("descriptor-present caller records = %+v", records)
	}
	result := records[0]
	consumerDigest := sha256.Sum256([]byte(t40r1DescriptorGitBlobFiles[t40r1DescriptorGitBlobPath]))
	consumerBlobDigest := "sha256:" + hex.EncodeToString(consumerDigest[:])

	witness := t40r1DescriptorGitBlobWitness{
		Schema:  t40r1DescriptorGitBlobSchema,
		Method:  "build and store-publish a real physical candidate generation, materialize and reopen one declaration-backed gRPC descriptor from immutable Git inputs, select its exact consumer leaf through the production provider, execute one pair with the default Git blob reader, and reread the installed result artifact",
		Profile: "physical-grpc-descriptor-pair-v1",
		Candidate: t40r1DescriptorGitBlobCandidate{
			CorpusFiles:           manifest.Corpus.RegularCount,
			CallerRecords:         t40r1DescriptorCallerRecordCount(manifest.CallerLeaves),
			CallerLeaves:          len(manifest.CallerLeaves),
			ProviderManifestExact: plan.Identity() == candidatePointer.ManifestDigest,
			ProviderControlExact:  plan.CandidateControlRevision() == candidatePointer.ControlRevision,
			SelectedLeaf: t40r1CallerPhysicalLeaf{
				Name: selectedLeaf.Name, Ordinal: selectedLeaf.Ordinal,
				Prefix: selectedLeaf.Prefix, PrefixBits: selectedLeaf.PrefixBits,
				RecordCount:   selectedLeaf.RecordCount,
				DeclaredBytes: selectedLeaf.DeclaredBytes,
				ContentBytes:  selectedLeaf.ContentBytes,
				ContentDigest: selectedLeaf.ContentDigest,
			},
			SelectedRecords:     selectedRecords,
			SelectedPath:        t40r1DescriptorGitBlobPath,
			SelectedObjectExact: result.ObjectID == objects[t40r1DescriptorGitBlobPath],
		},
		Resolver: t40r1DescriptorGitBlobResolver{
			PublicationCurrent:       resolverCurrent,
			ManifestMembers:          len(resolverPublication.Manifest().Members),
			ManifestDigestExact:      resolverPublication.Manifest().Digest == resolverPointer.ManifestDigest,
			GenerationDigestExact:    resolverView.GenerationDigest() == resolverPointer.GenerationDigest,
			MaterializationBlobReads: resolverBlobReads,
			MaterializationBlobBytes: resolverBlobBytes,
			Descriptors:              len(descriptors), Protocol: string(resolverView.Protocol()),
			ImportPath: descriptor.ImportPath, ClientType: descriptor.ClientType,
			Method: descriptor.Method, Operation: descriptor.Operation,
			DeclarationPath:    descriptor.DeclarationPath,
			DeclarationLineage: descriptor.DeclarationLineage,
			GeneratedPath:      descriptor.GeneratedPath,
			GeneratedObjectExact: generatedExact &&
				descriptor.GeneratedObjectID == objects[t40r1DescriptorGeneratedPath],
		},
		Pair: t40r1DescriptorGitBlobPair{
			ExpectedPairs: len(pairs), ExecutedDomain: selectedPair.Adapter.Domain,
			ExecutedVersion:      selectedPair.Adapter.Version,
			ExecutedProtocol:     selectedPair.Adapter.Protocol,
			DefaultGitBlobReader: true,
			RecordCount:          receipt.RecordCount, ResultCount: receipt.ResultCount,
			AbstentionCount:   receipt.AbstentionCount,
			CoverageRecords:   receipt.CoverageRecordCount,
			SourceBlobReads:   receipt.SourceBlobReads,
			SourceBlobBytes:   receipt.SourceBlobBytes,
			OutOfLeafReads:    receipt.OutOfLeafReads,
			ArtifactInstalled: true, ResultPath: result.Path,
			ResultObjectExact:     result.ObjectID == objects[t40r1DescriptorGitBlobPath],
			ResultPredicate:       result.Fact.Assertion.Predicate,
			ResultOperation:       result.Fact.Assertion.Object,
			ResultLineage:         result.Fact.Assertion.Lineage,
			ResultBlobDigestExact: result.Fact.Atom.BlobDigest == consumerBlobDigest,
		},
		Boundary: "descriptor_present_resolver_git_blob_pair_execution",
	}
	witness.ClearsBoundary =
		witness.Candidate.CorpusFiles == len(t40r1DescriptorGitBlobFiles) &&
			witness.Candidate.CallerRecords == 6 && witness.Candidate.CallerLeaves == 4 &&
			witness.Candidate.ProviderManifestExact && witness.Candidate.ProviderControlExact &&
			witness.Candidate.SelectedRecords == 1 && witness.Candidate.SelectedObjectExact &&
			witness.Resolver.PublicationCurrent && witness.Resolver.ManifestMembers == 2 &&
			witness.Resolver.ManifestDigestExact && witness.Resolver.GenerationDigestExact &&
			witness.Resolver.MaterializationBlobReads == 4 && witness.Resolver.Descriptors == 1 &&
			witness.Resolver.GeneratedObjectExact && witness.Pair.ExpectedPairs == 4 &&
			witness.Pair.DefaultGitBlobReader && witness.Pair.RecordCount == 1 &&
			witness.Pair.ResultCount == 1 && witness.Pair.AbstentionCount == 0 &&
			witness.Pair.CoverageRecords == 0 && witness.Pair.SourceBlobReads == 1 &&
			witness.Pair.SourceBlobBytes == int64(len(t40r1DescriptorGitBlobFiles[t40r1DescriptorGitBlobPath])) &&
			witness.Pair.OutOfLeafReads == 0 && witness.Pair.ArtifactInstalled &&
			witness.Pair.ResultObjectExact && witness.Pair.ResultPredicate == "CALLS_OPERATION" &&
			witness.Pair.ResultOperation == t40r1DescriptorOperation &&
			witness.Pair.ResultLineage == t40r1DescriptorLineage &&
			witness.Pair.ResultBlobDigestExact
	if !witness.ClearsBoundary {
		t.Fatalf("descriptor-present Git-blob diagnostic did not clear: %+v", witness)
	}
	measurement.CandidateDisk = t40r1CallerProvider96DirectoryBytes(t, candidateRoot)
	measurement.ResolverDisk = t40r1CallerProvider96DirectoryBytes(t, resolverRoot)
	measurement.CallerDisk = t40r1CallerProvider96DirectoryBytes(t, callerRoot)
	measurement.RepositoryDisk = t40r1CallerProvider96DirectoryBytes(t, repositoryDir)
	return witness, measurement
}

