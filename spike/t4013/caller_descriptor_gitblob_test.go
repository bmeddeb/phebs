func t40r1DescriptorGitBlobRepository(
	t *testing.T,
	ctx context.Context,
) (string, string, map[string]string) {
	t.Helper()
	directory := filepath.Join(t.TempDir(), "repository.git")
	if err := os.MkdirAll(directory, 0o700); err != nil {
		t.Fatal(err)
	}
	t40r1CallerPartitionedGit(t, ctx, directory, "init", "--bare", "-q")
	paths := make([]string, 0, len(t40r1DescriptorGitBlobFiles))
	for path := range t40r1DescriptorGitBlobFiles {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	command := exec.CommandContext(ctx, "git", "--git-dir", directory, "fast-import", "--quiet")
	command.Env = append(slices.DeleteFunc(os.Environ(), func(value string) bool {
		return strings.HasPrefix(value, "GIT_")
	}), "GIT_CONFIG_NOSYSTEM=1", "GIT_CONFIG_GLOBAL=/dev/null")
	stdin, err := command.StdinPipe()
	if err != nil {
		t.Fatal(err)
	}
	if err := command.Start(); err != nil {
		t.Fatal(err)
	}
	writer := bufio.NewWriterSize(stdin, 64<<10)
	var writeErr error
	for index, path := range paths {
		content := t40r1DescriptorGitBlobFiles[path]
		_, writeErr = fmt.Fprintf(writer, "blob\nmark :%d\ndata %d\n%s\n", index+1, len(content), content)
		if writeErr != nil {
			break
		}
	}
	message := "descriptor-present Git-blob pair execution"
	if writeErr == nil {
		_, writeErr = fmt.Fprintf(writer,
			"commit refs/heads/main\nmark :100\nauthor T40R1 Descriptor <t40r1-descriptor@example.invalid> 946684800 +0000\ncommitter T40R1 Descriptor <t40r1-descriptor@example.invalid> 946684800 +0000\ndata %d\n%s\n",
			len(message), message,
		)
	}
	for index, path := range paths {
		if writeErr != nil {
			break
		}
		_, writeErr = fmt.Fprintf(writer, "M 100644 :%d %s\n", index+1, path)
	}
	if writeErr == nil {
		_, writeErr = writer.WriteString("\ndone\n")
	}
	if flushErr := writer.Flush(); writeErr == nil {
		writeErr = flushErr
	}
	if closeErr := stdin.Close(); writeErr == nil {
		writeErr = closeErr
	}
	waitErr := command.Wait()
	if writeErr != nil || waitErr != nil {
		t.Fatalf("author descriptor Git repository: write=%v wait=%v", writeErr, waitErr)
	}
	commit := strings.TrimSpace(t40r1CallerPartitionedGit(
		t, ctx, directory, "rev-parse", "refs/heads/main",
	))
	objects := make(map[string]string, len(paths))
	for _, path := range paths {
		objects[path] = strings.TrimSpace(t40r1CallerPartitionedGit(
			t, ctx, directory, "rev-parse", commit+":"+path,
		))
	}
	return directory, commit, objects
}
