import { expect, test, type Page, type TestInfo } from '@playwright/test'
import { createRequire } from 'node:module'
import { codeHistoryFixture, historyRepo as repo, historyRef as ref } from './codeHistoryFixture'

const require = createRequire(import.meta.url)
async function check(page: Page, fixture: Awaited<ReturnType<typeof codeHistoryFixture>>, info: TestInfo, image = 'state.png') {
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  await page.evaluate(async () => {
    await document.fonts.ready
    await Promise.all(document.getAnimations().filter(animation => animation.effect?.getComputedTiming().iterations !== Infinity).map(animation => animation.finished.catch(() => {})))
  })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.addScriptTag({ path: require.resolve('axe-core/axe.min.js') })
  const violations = await page.evaluate(async () => {
    const axe = (window as unknown as { axe: { run: (options: unknown) => Promise<{ violations: unknown[] }> } }).axe
    return (await axe.run({ runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations
  })
  expect(violations).toEqual([])
  expect(fixture.errors).toEqual([])
  expect(fixture.unexpected).toEqual([])
  await page.screenshot({ path: info.outputPath(image), animations: 'disabled', caret: 'hide' })
}
function expectedOutage(fixture: Awaited<ReturnType<typeof codeHistoryFixture>>) {
  expect(fixture.errors.splice(0)).toEqual(['Failed to load resource: the server responded with a status of 503 (Service Unavailable)'])
}


const route = (kind: string, values: Record<string, string> = {}) => '/#/' + kind + '?' + new URLSearchParams({ repo, ...values })
async function lookup(page: Page, moves = 1) {
  const source = page.getByRole('textbox', { name: 'Source code for main.go' })
  await source.focus()
  for (let index = 0; index < moves; index++) await source.press('ArrowRight')
  await source.press('Enter')
}

test.beforeEach(async ({ page }, info) => {
  const width = info.title.endsWith('390') ? 390 : 1280
  await page.setViewportSize({ width, height: 900 })
  await page.emulateMedia({ colorScheme: width === 390 ? 'dark' : 'light', reducedMotion: 'reduce' })
  await page.clock.setFixedTime(new Date('2026-10-19T12:00:00Z'))
})
for (const width of [1280, 390]) {
  test(`history retries the initial and next page with exact pinned context ${width}`, async ({ page }, info) => {
    const fixture = await codeHistoryFixture(page)
    fixture.fail('/api/commits')
    await page.goto(route('history', { ref: 'main', path: 'main.go' }))
    await expect(page).toHaveTitle('phebs · History')
    await expect(page.getByRole('button', { name: 'Retry history page' })).toBeVisible()
    expectedOutage(fixture)
    await check(page, fixture, info, 'initial-error.png')
    fixture.fail('')
    await page.getByRole('button', { name: 'Retry history page' }).press('Enter')
    await expect(page.getByRole('button', { name: 'Load more' })).toBeVisible()
    fixture.fail('/api/commits')
    await page.getByRole('button', { name: 'Load more' }).press('Enter')
    await expect(page.getByRole('button', { name: 'Retry history page' })).toBeVisible()
    await expect(page.getByRole('link', { name: /Neutral change aaaaaaa/ })).toBeVisible()
    expectedOutage(fixture)
    await check(page, fixture, info, 'append-error.png')
    fixture.fail('')
    const started = Date.now()
    await page.getByRole('button', { name: 'Retry history page' }).press('Enter')
    await expect(page.getByRole('link', { name: /Neutral change ccccccc/ })).toBeVisible()
    console.log(JSON.stringify({ width, historyRetryMillis: Date.now() - started }))
    expect(fixture.requests.map(read => [read.query.ref, read.query.offset])).toEqual([['main', '0'], ['main', '0'], [ref, '2'], [ref, '2']])
    await check(page, fixture, info)
  })
  test(`history route changes discard a held page and survive back forward ${width}`, async ({ page }, info) => {
    const fixture = await codeHistoryFixture(page)
    await page.goto(route('history', { path: 'main.go', ref }))
    await expect(page.getByRole('button', { name: 'Load more' })).toBeVisible()
    fixture.hold('/api/commits')
    await page.getByRole('button', { name: 'Load more' }).press('Enter')
    await expect.poll(fixture.held).toBe(true)
    await page.goto(route('history', { path: 'current.go', ref: 'd'.repeat(40) }))
    await expect(page.getByRole('link', { name: /Neutral change ddddddd/ })).toBeVisible()
    await fixture.release()
    await expect(page.getByRole('link', { name: /Neutral change ccccccc/ })).toHaveCount(0)
    await page.goBack()
    await expect(page.getByRole('link', { name: /Neutral change aaaaaaa/ })).toBeVisible()
    await page.goForward()
    await expect(page.getByRole('link', { name: /Neutral change ddddddd/ })).toBeVisible()
    await check(page, fixture, info)
  })
  test(`commit pins a moving ref before reading the diff and supports keyboard patch scrolling ${width}`, async ({ page }, info) => {
    const fixture = await codeHistoryFixture(page)
    await page.goto(route('commit', { ref: 'main', path: 'main.go' }))
    await expect(page.getByRole('heading', { name: 'Neutral change aaaaaaa' })).toBeVisible()
    expect(fixture.requests.map(read => [read.path, read.query.ref ?? read.query.head])).toEqual([['/api/commit', 'main'], ['/api/diff', ref]])
    const patch = page.getByRole('group', { name: 'main.go patch text' })
    await patch.focus(); await patch.press('ArrowRight')
    await expect.poll(() => patch.evaluate(element => element.scrollLeft)).toBeGreaterThan(0)
    await check(page, fixture, info)
    await page.getByRole('link', { name: 'main.go', exact: true }).press('Enter')
    await expect(page.getByRole('textbox', { name: 'Source code for main.go' })).toBeVisible()
    expect(fixture.sources.at(-1)?.ref).toBe(ref)
  })
  test(`a crossed diff refuses then retries the exact commit ${width}`, async ({ page }, info) => {
    const fixture = await codeHistoryFixture(page)
    fixture.bad('diff')
    await page.goto(route('commit', { ref }))
    await expect(page.getByText('Invalid diff response', { exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Neutral change aaaaaaa' })).toHaveCount(0)
    await check(page, fixture, info, 'refusal.png')
    fixture.bad('')
    await page.getByRole('button', { name: 'Retry commit' }).press('Enter')
    await expect(page.getByRole('heading', { name: 'Neutral change aaaaaaa' })).toBeVisible()
    await check(page, fixture, info)
  })
  test(`blame retries and names repeated commit links ${width}`, async ({ page }, info) => {
    const fixture = await codeHistoryFixture(page)
    fixture.fail('/api/blame')
    await page.goto(route('blame', { path: 'main.go', ref }))
    await expect(page.getByRole('button', { name: 'Retry blame' })).toBeVisible()
    expectedOutage(fixture)
    await check(page, fixture, info, 'error.png')
    fixture.fail('')
    await page.getByRole('button', { name: 'Retry blame' }).press('Enter')
    await expect(page.getByText('package current 2', { exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Commit aaaaaaaa', exact: true })).toBeVisible()
    await check(page, fixture, info)
  })
  test(`blame discards a late old path response ${width}`, async ({ page }, info) => {
    const fixture = await codeHistoryFixture(page)
    fixture.hold('/api/blame')
    await page.goto(route('blame', { path: 'old.go', ref }))
    await expect.poll(fixture.held).toBe(true)
    await page.goto(route('blame', { path: 'current.go', ref }))
    await expect(page.getByText('package current 1', { exact: true })).toBeVisible()
    await fixture.release()
    await expect(page.getByText('package obsolete 1', { exact: true })).toHaveCount(0)
    await expect(page.getByRole('link', { name: 'current.go', exact: true })).toHaveAttribute('href', new RegExp('ref=' + ref))
    await check(page, fixture, info)
  })
  test(`keyboard symbol lookup retries its exact position and follows an immutable definition ${width}`, async ({ page }, info) => {
    const fixture = await codeHistoryFixture(page)
    fixture.fail('/api/find_definitions')
    await page.goto(route('file', { path: 'main.go', ref }))
    const source = page.getByRole('textbox', { name: 'Source code for main.go' })
    await source.focus()
    for (const key of ['End', 'Home', 'ArrowDown', 'ArrowUp', 'x']) await source.press(key)
    await expect(source).toContainText('package alpha')
    await lookup(page)
    await expect(page.getByRole('button', { name: 'Retry code navigation' })).toBeVisible()
    expectedOutage(fixture)
    await expect(source).toBeFocused()
    await check(page, fixture, info, 'error.png')
    fixture.fail('')
    await page.getByRole('button', { name: 'Retry code navigation' }).press('Enter')
    await expect(page.getByText('Symbol at 1', { exact: true })).toBeVisible()
    const reads = fixture.requests.filter(read => read.path.includes('find_') || read.path === '/api/hover')
    expect(reads).toHaveLength(6)
    expect(reads.every(read => read.query.ref === ref && read.query.line === '0' && read.query.character === '1' && read.query.encoding === 'utf16')).toBe(true)
    await check(page, fixture, info)
    await page.getByRole('complementary', { name: 'Code navigation' }).getByRole('link', { name: 'lib.go:3' }).first().press('Enter')
    await expect(page.getByRole('textbox', { name: 'Source code for lib.go' })).toBeVisible()
    await expect(page).toHaveURL(new RegExp('ref=' + ref + '&L=3'))
    expect(fixture.sources.at(-1)).toEqual({ repo, ref, path: 'lib.go' })
  })
  test(`crossed symbol locations refuse and newer selections discard held replies ${width}`, async ({ page }, info) => {
    const fixture = await codeHistoryFixture(page)
    fixture.bad('location')
    await page.goto(route('file', { path: 'main.go', ref }))
    await lookup(page)
    await expect(page.getByText('Invalid code navigation response', { exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'lib.go:3' })).toHaveCount(0)
    await check(page, fixture, info, 'refusal.png')
    fixture.bad(''); fixture.hold('/api/find_definitions')
    await page.getByRole('button', { name: 'Retry code navigation' }).press('Enter')
    await expect.poll(fixture.held).toBe(true)
    await lookup(page)
    await expect(page.getByText('Symbol at 2', { exact: true })).toBeVisible()
    await fixture.release()
    await expect(page.getByText('Symbol at 1', { exact: true })).toHaveCount(0)
    await check(page, fixture, info)
  })
}
