import { expect, test, type Page, type TestInfo } from '@playwright/test'
import { createRequire } from 'node:module'
import { settingsAuthFixture } from './settingsAuthFixture'

const require = createRequire(import.meta.url)
async function check(page: Page, fixture: Awaited<ReturnType<typeof settingsAuthFixture>>, info: TestInfo, image = 'state.png') {
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  await page.evaluate(async () => {
    await document.fonts.ready
    await Promise.all(document.getAnimations().filter(animation => animation.effect?.getComputedTiming().iterations !== Infinity).map(animation => animation.finished.catch(() => {})))
  })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.addScriptTag({ path: require.resolve('axe-core/axe.min.js') })
  const violations = await page.evaluate(async () => {
    const axe = (window as unknown as { axe: { run: (options: unknown) => Promise<{ violations: unknown[] }> } }).axe
    return (await axe.run({ runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations
  })
  expect(violations).toEqual([])
  expect(fixture.errors).toEqual([])
  expect(fixture.unexpected).toEqual([])
  await page.screenshot({ path: info.outputPath(image), animations: 'disabled', caret: 'hide' })
}
function expectedOutage(fixture: Awaited<ReturnType<typeof settingsAuthFixture>>) {
  expect(fixture.errors.splice(0)).toEqual(['Failed to load resource: the server responded with a status of 503 (Service Unavailable)'])
}
async function refresh(page: Page) { await page.evaluate(() => window.dispatchEvent(new CustomEvent('phebs-auth-required'))) }
async function createKey(page: Page, name = 'Neutral client') {
  await page.getByLabel('Key name', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Create key', exact: true }).press('Enter')
  await expect(page.getByLabel('New API key token')).toBeVisible()
}

test.beforeEach(async ({ page }, info) => {
  const width = info.title.endsWith('390') ? 390 : 1280
  await page.setViewportSize({ width, height: 900 })
  await page.emulateMedia({ colorScheme: width === 390 ? 'dark' : 'light', reducedMotion: 'reduce' })
  await page.clock.setFixedTime(new Date('2026-10-19T12:00:00Z'))
})
for (const width of [1280, 390]) {
  test(`authentication retries status then signs in and out with CSRF ${width}`, async ({ page }, info) => {
    const fixture = await settingsAuthFixture(page)
    fixture.authenticated(false); fixture.fail('/api/auth/status')
    await page.goto('/#/settings')
    await expect(page).toHaveTitle('phebs · Settings')
    await expect(page.getByRole('button', { name: 'Retry authentication' })).toBeVisible()
    expectedOutage(fixture)
    await check(page, fixture, info, 'auth-error.png')
    fixture.fail('')
    await page.getByRole('button', { name: 'Retry authentication' }).press('Enter')
    await page.getByLabel('Email', { exact: true }).fill('reader0@localhost.test')
    await page.getByLabel('Password', { exact: true }).fill('neutral fixture password')
    await page.getByRole('button', { name: 'Sign in', exact: true }).press('Enter')
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Sign out', exact: true }).press('Enter')
    await expect(page.getByRole('button', { name: 'Sign in', exact: true })).toBeVisible()
    expect(fixture.requests.filter(read => read.path === '/api/auth/login')).toHaveLength(1)
    await check(page, fixture, info)
  })
  test(`superseded logout cannot clear the newer browser session cookie ${width}`, async ({ page, context }, info) => {
    const fixture = await settingsAuthFixture(page)
    await context.addCookies([{ name: 'settings-fixture-session', value: 'original', url: 'http://127.0.0.1:4176' }])
    await page.goto('/#/settings')
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    fixture.hold('/api/auth/logout')
    await page.getByRole('button', { name: 'Sign out', exact: true }).press('Enter')
    await expect.poll(fixture.held).toBe(true)
    await refresh(page)
    await page.getByLabel('Email', { exact: true }).fill('reader0@localhost.test')
    await page.getByLabel('Password', { exact: true }).fill('neutral fixture password')
    await page.getByRole('button', { name: 'Sign in', exact: true }).press('Enter')
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    expect((await context.cookies()).find(cookie => cookie.name === 'settings-fixture-session')?.value).toBe('current')
    await fixture.release()
    await expect.poll(async () => (await context.cookies()).find(cookie => cookie.name === 'settings-fixture-session')?.value).toBe('current')
    await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
    await check(page, fixture, info)
  })
  test(`malformed auth status refuses and retries without entering Settings ${width}`, async ({ page }, info) => {
    const fixture = await settingsAuthFixture(page)
    fixture.badStatus(true)
    await page.goto('/#/settings')
    await expect(page.getByText(/Invalid authentication status/)).toBeVisible()
    expect(fixture.requests.some(read => read.path === '/api/auth/keys')).toBe(false)
    await check(page, fixture, info, 'invalid-status.png')
    fixture.badStatus(false)
    await page.getByRole('button', { name: 'Retry authentication' }).press('Enter')
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    await check(page, fixture, info)
  })
  test(`initial key inventory gates creation and revocation removes the matching token ${width}`, async ({ page }, info) => {
    const fixture = await settingsAuthFixture(page)
    fixture.hold('/api/auth/keys')
    await page.goto('/#/settings')
    await expect.poll(fixture.held).toBe(true)
    await page.getByLabel('Key name', { exact: true }).fill('Neutral client')
    await expect(page.getByRole('button', { name: 'Create key', exact: true })).toBeDisabled()
    expect(fixture.requests.filter(read => read.method === 'POST')).toEqual([])
    await fixture.release()
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    fixture.hold('/api/auth/keys')
    await page.getByRole('button', { name: 'Create key', exact: true }).press('Enter')
    await expect.poll(fixture.held).toBe(true)
    await page.getByLabel('Key name', { exact: true }).fill('Next client')
    await fixture.release()
    await expect(page.getByLabel('New API key token')).toBeVisible()
    await expect(page.getByLabel('Key name', { exact: true })).toHaveValue('Next client')
    await page.getByRole('button', { name: 'Revoke Neutral client', exact: true }).press('Enter')
    await page.getByRole('button', { name: 'Revoke', exact: true }).press('Enter')
    await expect(page.getByLabel('New API key token')).toHaveCount(0)
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    expect(fixture.requests.filter(read => read.path.startsWith('/api/auth/keys')).map(read => read.method)).toEqual(['GET', 'POST', 'DELETE'])
    await check(page, fixture, info)
  })
  test(`key inventory failure retries exactly the read ${width}`, async ({ page }, info) => {
    const fixture = await settingsAuthFixture(page)
    fixture.fail('/api/auth/keys')
    await page.goto('/#/settings')
    await expect(page.getByRole('button', { name: 'Retry API keys' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Create key', exact: true })).toBeDisabled()
    expectedOutage(fixture)
    await check(page, fixture, info, 'keys-error.png')
    fixture.fail('')
    const started = Date.now()
    await page.getByRole('button', { name: 'Retry API keys' }).press('Enter')
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    console.log(JSON.stringify({ width, keyRetryMillis: Date.now() - started }))
    expect(fixture.requests.filter(read => read.path === '/api/auth/keys').map(read => read.method)).toEqual(['GET', 'GET'])
    await check(page, fixture, info)
  })
  test(`user and role changes clear private Settings while same-user refresh retains it ${width}`, async ({ page }, info) => {
    const fixture = await settingsAuthFixture(page)
    await page.goto('/#/settings')
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    await createKey(page)
    await refresh(page)
    await expect.poll(() => fixture.requests.filter(read => read.path === '/api/auth/status').length).toBe(2)
    await expect(page.getByLabel('New API key token')).toBeVisible()
    expect(fixture.requests.filter(read => read.path === '/api/auth/keys')).toHaveLength(2) // list + creation
    fixture.user(1)
    await refresh(page)
    await expect(page.getByLabel('New API key token')).toHaveCount(0)
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    await createKey(page, 'Second client')
    fixture.admin(true)
    await refresh(page)
    await expect(page.getByRole('heading', { name: 'Lifecycle maintenance' })).toBeVisible()
    await expect(page.getByLabel('New API key token')).toHaveCount(0)
    await expect.poll(() => fixture.requests.filter(read => read.path === '/api/version').length).toBe(3)
    await check(page, fixture, info)
  })
  test(`administrator lifecycle retry keeps key inventory independent ${width}`, async ({ page }, info) => {
    const fixture = await settingsAuthFixture(page)
    fixture.admin(true); fixture.fail('/api/lifecycle-status')
    await page.goto('/#/settings')
    await expect(page.getByRole('button', { name: 'Retry lifecycle status' })).toBeVisible()
    await expect(page.getByText('No API keys.', { exact: true })).toBeVisible()
    expectedOutage(fixture)
    await check(page, fixture, info, 'lifecycle-error.png')
    fixture.fail('')
    await page.getByRole('button', { name: 'Retry lifecycle status' }).press('Enter')
    await expect(page.getByText('Collection disabled', { exact: true })).toBeVisible()
    expect(fixture.requests.filter(read => read.path === '/api/lifecycle-status')).toHaveLength(2)
    expect(fixture.requests.filter(read => read.path === '/api/auth/keys')).toHaveLength(1)
    await check(page, fixture, info)
  })
}
