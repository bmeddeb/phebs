import { expect, test, type Page, type TestInfo } from '@playwright/test'
import { createRequire } from 'node:module'
import { auditAnalyticsFixture } from './auditAnalyticsFixture'

const require = createRequire(import.meta.url)
async function check(page: Page, fixture: Awaited<ReturnType<typeof auditAnalyticsFixture>>, info: TestInfo, image = 'state.png') {
  await expect(page.locator('vite-error-overlay')).toHaveCount(0)
  await page.evaluate(async () => {
    await document.fonts.ready
    await Promise.all(document.getAnimations().filter(animation => animation.effect?.getComputedTiming().iterations !== Infinity).map(animation => animation.finished.catch(() => {})))
  })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.addScriptTag({ path: require.resolve('axe-core/axe.min.js') })
  const violations = await page.evaluate(async () => {
    const axe = (window as unknown as { axe: { run: (options: unknown) => Promise<{ violations: unknown[] }> } }).axe
    return (await axe.run({ runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations
  })
  expect(violations).toEqual([])
  expect(fixture.errors).toEqual([])
  expect(fixture.unexpected).toEqual([])
  await page.screenshot({ path: info.outputPath(image), animations: 'disabled', caret: 'hide' })
}
function expectedOutage(fixture: Awaited<ReturnType<typeof auditAnalyticsFixture>>) {
  expect(fixture.errors.splice(0)).toEqual(['Failed to load resource: the server responded with a status of 503 (Service Unavailable)'])
}

test.beforeEach(async ({ page }, info) => {
  const width = info.title.endsWith('390') ? 390 : 1280
  await page.setViewportSize({ width, height: 900 })
  await page.emulateMedia({ colorScheme: width === 390 ? 'dark' : 'light', reducedMotion: 'reduce' })
  await page.clock.setFixedTime(new Date('2026-10-19T12:00:00Z'))
})
for (const width of [1280, 390]) {
  test(`audit paging advances beyond overlapping rows with keyboard navigation ${width}`, async ({ page }, info) => {
    const fixture = await auditAnalyticsFixture(page)
    await page.goto('/#/audit')
    await expect(page).toHaveTitle('phebs · Audit log')
    await page.getByRole('button', { name: 'Load more' }).press('Enter')
    await expect(page.getByRole('row')).toHaveCount(4)
    await page.getByRole('button', { name: 'Load more' }).press('Enter')
    await expect(page.getByRole('row')).toHaveCount(5)
    expect(fixture.requests).toEqual(['/api/audit?offset=0&limit=50', '/api/audit?offset=2&limit=50', '/api/audit?offset=4&limit=50'])
    if (width === 390) {
      const region = page.getByRole('region', { name: 'Audit events' })
      await region.focus()
      await region.press('ArrowRight')
      await expect.poll(() => region.evaluate(element => element.scrollLeft)).toBeGreaterThan(0)
    }
    await check(page, fixture, info)
    await page.goto('/#/analytics')
    await expect(page.getByText('Searches on 2026-10-19 (UTC)', { exact: true })).toBeVisible()
    await page.goBack()
    await expect(page.getByRole('button', { name: 'Load more' })).toBeVisible()
    await page.goForward()
    await expect(page.getByText('Searches on 2026-10-19 (UTC)', { exact: true })).toBeVisible()
    await check(page, fixture, info, 'analytics.png')
  })
  test(`audit initial and append failures retry the exact page ${width}`, async ({ page }, info) => {
    const fixture = await auditAnalyticsFixture(page)
    fixture.fail('/api/audit')
    await page.goto('/#/audit')
    await expect(page.getByRole('button', { name: 'Retry audit page' })).toBeVisible()
    expectedOutage(fixture)
    await check(page, fixture, info, 'initial-error.png')
    fixture.fail('')
    await page.getByRole('button', { name: 'Retry audit page' }).press('Enter')
    await expect(page.getByRole('button', { name: 'Load more' })).toBeVisible()
    fixture.fail('/api/audit')
    await page.getByRole('button', { name: 'Load more' }).press('Enter')
    await expect(page.getByRole('button', { name: 'Retry audit page' })).toBeVisible()
    await expect(page.getByRole('row')).toHaveCount(3)
    expectedOutage(fixture)
    await check(page, fixture, info, 'append-error.png')
    fixture.fail('')
    const started = Date.now()
    await page.getByRole('button', { name: 'Retry audit page' }).press('Enter')
    await expect(page.getByRole('row')).toHaveCount(4)
    console.log(JSON.stringify({ width, auditRetryMillis: Date.now() - started }))
    expect(fixture.requests).toEqual(['/api/audit?offset=0&limit=50', '/api/audit?offset=0&limit=50', '/api/audit?offset=2&limit=50', '/api/audit?offset=2&limit=50'])
    await check(page, fixture, info)
  })
  test(`malformed audit refuses duplicate rows and can retry ${width}`, async ({ page }, info) => {
    const fixture = await auditAnalyticsFixture(page)
    fixture.invalid('audit')
    await page.goto('/#/audit')
    await expect(page.getByText('Invalid audit response', { exact: true })).toBeVisible()
    await expect(page.getByText('neutral.action.1', { exact: true })).toHaveCount(0)
    await expect(page.getByText('No recorded actions yet.')).toHaveCount(0)
    await check(page, fixture, info, 'invalid.png')
    fixture.invalid('')
    await page.getByRole('button', { name: 'Retry audit page' }).press('Enter')
    await expect(page.getByRole('row')).toHaveCount(3)
    await check(page, fixture, info)
  })
  test(`analytics failures and malformed counts retry without showing false totals ${width}`, async ({ page }, info) => {
    const fixture = await auditAnalyticsFixture(page)
    fixture.fail('/api/analytics')
    await page.goto('/#/analytics')
    await expect(page.getByRole('button', { name: 'Retry analytics' })).toBeVisible()
    expectedOutage(fixture)
    await check(page, fixture, info, 'outage.png')
    fixture.fail(''); fixture.invalid('analytics')
    await page.getByRole('button', { name: 'Retry analytics' }).press('Enter')
    await expect(page.getByText('Invalid analytics response', { exact: true })).toBeVisible()
    await expect(page.getByText('Searches (30d)', { exact: true })).toHaveCount(0)
    await check(page, fixture, info, 'invalid.png')
    fixture.invalid('')
    const started = Date.now()
    await page.getByRole('button', { name: 'Retry analytics' }).press('Enter')
    await expect(page.getByText('Searches on 2026-10-19 (UTC)', { exact: true })).toBeVisible()
    console.log(JSON.stringify({ width, analyticsRetryMillis: Date.now() - started }))
    await expect(page.getByRole('img', { name: '2026-10-18: 0 searches' })).toBeVisible()
    expect(fixture.requests).toEqual(Array(3).fill('/api/analytics?days=30'))
    await check(page, fixture, info)
  })
  test(`access loss abandons an in-flight audit page and keeps admin reads gated ${width}`, async ({ page }, info) => {
    const fixture = await auditAnalyticsFixture(page)
    await page.goto('/#/audit')
    await expect(page.getByRole('row')).toHaveCount(3)
    fixture.holdAudit()
    await page.getByRole('button', { name: 'Load more' }).press('Enter')
    await expect.poll(fixture.held).toBe(true)
    fixture.admin(false)
    await page.evaluate(() => window.dispatchEvent(new CustomEvent('phebs-auth-required')))
    await expect(page.getByText('The audit log requires administrator access.')).toBeVisible()
    await fixture.release()
    await page.goto('/#/analytics')
    await expect(page.getByText('Analytics requires administrator access.')).toBeVisible()
    expect(fixture.requests).toHaveLength(2)
    await check(page, fixture, info, 'non-admin.png')
    fixture.admin(true)
    await page.evaluate(() => window.dispatchEvent(new CustomEvent('phebs-auth-required')))
    await expect(page.getByText('Searches on 2026-10-19 (UTC)', { exact: true })).toBeVisible()
    await page.goto('/#/audit')
    await expect(page.getByRole('row')).toHaveCount(3)
    await expect(page.getByText('neutral.action.99', { exact: true })).toHaveCount(0)
    await check(page, fixture, info)
  })
  test(`missing daily analytics remains an explicit gap ${width}`, async ({ page }, info) => {
    const fixture = await auditAnalyticsFixture(page)
    fixture.empty()
    await page.goto('/#/analytics')
    await expect(page.getByText('Unavailable', { exact: true })).toBeVisible()
    await expect(page.getByText('No daily counts returned.', { exact: true })).toBeVisible()
    await expect(page.getByText('Searches today', { exact: true })).toHaveCount(0)
    await check(page, fixture, info)
  })
}
