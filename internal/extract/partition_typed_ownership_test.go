// T47.2i real-store regression: a member partition of a domain that also owns
// a typed-input partition must not repeat syntax fallback. Run 20261011d
// proved the defect sequentially: the member partition staged
// UNRESOLVED_CALLER claims with resolution "syntax" and the typed partition
// staged the same assertion identities (same predicate, subject, object, and
// lineage — the span expansion is identical on both lanes) with resolution
// "scip"; the differing Detail JSON produced different attribute keys and the
// store's ENFORCE attribute_conflict check refused the run. These tests drive
// the production SparseSource + EvidencePartitionExecutor against one fresh
// supervised SurrealDB child per scenario and assert the ownership restored by
// T47.2i: the member partition stages nothing, the typed partition owns every
// claim once with truthful per-span resolution, and no order or interleaving
// of the two partitions can collide.

