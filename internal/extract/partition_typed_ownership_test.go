// stagedRecorder wraps one real Surreal store and retains every staged
// assertion batch so the test can attribute staged claims to partitions.
// Concurrent executions share the recorder; only totals are asserted there.
type stagedRecorder struct {
	*store.Surreal
	ordinal atomic.Int64
	mu      sync.Mutex
	chunks  []stagedChunk
}

type stagedChunk struct {
	ordinal int
	asserts []store.Assertion
}

func (recorder *stagedRecorder) AddEvidenceChunk(
	ctx context.Context, runID, chunkID string, factCount int,
	atoms []store.EvidenceAtom, assocs []store.SnapshotEvidence, asserts []store.Assertion,
) error {
	err := recorder.Surreal.AddEvidenceChunk(ctx, runID, chunkID, factCount, atoms, assocs, asserts)
	recorder.mu.Lock()
	recorder.chunks = append(recorder.chunks, stagedChunk{
		ordinal: int(recorder.ordinal.Load()), asserts: asserts,
	})
	recorder.mu.Unlock()
	return err
}

func (recorder *stagedRecorder) stagedAsserts(ordinal int) []store.Assertion {
	recorder.mu.Lock()
	defer recorder.mu.Unlock()
	var result []store.Assertion
	for _, chunk := range recorder.chunks {
		if chunk.ordinal == ordinal {
			result = append(result, chunk.asserts...)
		}
	}
	return result
}

func (recorder *stagedRecorder) totalStaged() int {
	recorder.mu.Lock()
	defer recorder.mu.Unlock()
	total := 0
	for _, chunk := range recorder.chunks {
		total += len(chunk.asserts)
	}
	return total
}

// typedOwnershipCorpus is the immutable commit-bound corpus behind the
// SparseSource OpenCorpus callback.
type typedOwnershipCorpus struct {
	repo, commit string
	files        map[string][]byte
}

func (corpus typedOwnershipCorpus) RepoName() string { return corpus.repo }
func (corpus typedOwnershipCorpus) Commit() string   { return corpus.commit }

func (corpus typedOwnershipCorpus) WalkFiles(ctx context.Context, visit func(string) error) error {
	paths := make([]string, 0, len(corpus.files))
	for path := range corpus.files {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		if err := ctx.Err(); err != nil {
			return err
		}
		if err := visit(path); err != nil {
			return err
		}
	}
	return nil
}

func (corpus typedOwnershipCorpus) Read(_ context.Context, path string) (sdk.Blob, error) {
	content, ok := corpus.files[path]
	if !ok {
		return sdk.Blob{}, store.ErrNotFound
	}
	return typedOwnershipBlob(content), nil
}

func (corpus typedOwnershipCorpus) ReadSCIPIndex(ctx context.Context) (sdk.SCIPInput, error) {
	blob, err := corpus.Read(ctx, "index.scip")
	if err != nil {
		return sdk.SCIPInput{Present: false}, nil
	}
	return sdk.SCIPInput{Path: "index.scip", Blob: blob, Present: true}, nil
}

func typedOwnershipBlob(content []byte) sdk.Blob {
	sum := sha256.Sum256(content)
	return sdk.Blob{Content: string(content), Digest: "sha256:" + hex.EncodeToString(sum[:])}
}

type typedOwnershipFixture struct {
	repository    string
	commit        string
	unitDigest    string
	sparse        *candidate.SparsePublication
	files         map[string][]byte
	plan          candidate.DomainResultPlan
	memberOrdinal int
	typedOrdinal  int // -1 for the syntax-only domain (no typed input)
}

// buildTypedOwnershipFixture commits a flat-layout repo: go.mod, one generated
// gRPC client, one caller file, and (optionally) a partial SCIP index that
// references SayHello only. Flat layout keeps every admitted record in one
// directory artifact, so the domain has exactly one member partition — the
// same shape as the run 20261011d collision pair.
func buildTypedOwnershipFixture(
	t *testing.T,
	repositoryDirectory, candidateDirectory, sparseDirectory string,
	typed bool,
) typedOwnershipFixture {
	t.Helper()
	files := map[string][]byte{
		"go.mod":             []byte("module " + typedOwnershipModule + "\n\ngo 1.24\n"),
		"greeter_grpc.pb.go": []byte(typedOwnershipGenerated),
		"main.go":            []byte(typedOwnershipCaller),
	}
	if typed {
		files["index.scip"] = typedOwnershipIndex(t)
	}
	commit := seedTypedOwnershipRepository(t, repositoryDirectory, files)

	policy := candidate.Policy{
		Domain: typedOwnershipDomain, Version: typedOwnershipVersion,
		EnumerationPolicy: "grpc-caller-paths-v1", Plane: candidate.PlaneRepository,
		Enumerate: func(path string) bool {
			return path == "go.mod" || strings.HasSuffix(path, ".go")
		},
		Required: func(path string) bool {
			return path == "go.mod" || strings.HasSuffix(path, ".go")
		},
	}
	if typed {
		policy.TypedInputs = []string{"scip"}
	}
	// candidate.Build and BuildSparseRoot require their output directories to
	// pre-exist and be empty (requireEmptyDirectory).
	if err := os.MkdirAll(candidateDirectory, 0o700); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(sparseDirectory, 0o700); err != nil {
		t.Fatal(err)
	}
	policies := []candidate.Policy{policy}
	identities, err := candidate.PolicyIdentities(policies)
	if err != nil {
		t.Fatal(err)
	}
	policyDigest, err := candidate.PolicyDigest(identities)
	if err != nil {
		t.Fatal(err)
	}
	manifest, err := candidate.Build(t.Context(), candidate.Request{
		RepoDir: repositoryDirectory, OutputDir: candidateDirectory,
		Repository: typedOwnershipRepository, Commit: commit, Policies: policies,
	})
	if err != nil {
		t.Fatal(err)
	}
	publication, err := candidate.Open(candidateDirectory, candidate.Expected{
		Repository: typedOwnershipRepository, Commit: commit, Policies: identities,
		PolicyDigest: policyDigest, GenerationDigest: manifest.GenerationDigest,
		ManifestDigest: manifest.Digest,
	})
	if err != nil {
		t.Fatal(err)
	}
	sparseRoot, err := candidate.BuildSparseRoot(t.Context(), sparseDirectory, publication, nil)
	if err != nil {
		t.Fatal(err)
	}
	sparse, err := candidate.OpenSparse(
		t.Context(), sparseDirectory, candidateDirectory, publication.State(),
		sparseRoot.Digest, nil,
	)
	if err != nil {
		t.Fatal(err)
	}
	domain, err := sparse.OpenDomain(t.Context(), typedOwnershipDomain, typedOwnershipVersion)
	if err != nil {
		t.Fatal(err)
	}
	extractionPolicyDigest, err := candidate.ExtractionPolicyDigest(policyDigest, false, true)
	if err != nil {
		t.Fatal(err)
	}
	plan, err := extractionpublication.BuildReservedPlan(domain, candidate.DomainResultAuthority{
		SourceGenerationDigest:      "sha256:" + strings.Repeat("1", 64),
		ObservationGenerationDigest: "sha256:" + strings.Repeat("2", 64),
		ExtractorVersion:            typedOwnershipVersion,
		ExtractionPolicyDigest:      extractionPolicyDigest,
	}, true)
	if err != nil {
		t.Fatal(err)
	}
	fixture := typedOwnershipFixture{
		repository: typedOwnershipRepository, commit: commit,
		unitDigest: manifest.UnitDigest, sparse: sparse, files: files,
		plan: plan, memberOrdinal: -1, typedOrdinal: -1,
	}
	for _, partition := range domain.Partitions() {
		switch partition.Kind {
		case candidate.PartitionKindTypedInput:
			fixture.typedOrdinal = partition.Ordinal
		case candidate.PartitionKindCandidateMember:
			var hasCaller bool
			if readErr := domain.ReadPartition(t.Context(), partition.Ordinal, func(record candidate.Record) error {
				if record.Path == "main.go" {
					hasCaller = true
				}
				return nil
			}); readErr != nil {
				t.Fatal(readErr)
			}
			if hasCaller {
				fixture.memberOrdinal = partition.Ordinal
			}
		}
	}
	if fixture.memberOrdinal < 0 {
		t.Fatal("fixture has no member partition containing main.go")
	}
	if typed && fixture.typedOrdinal < 0 {
		t.Fatal("typed fixture has no typed-input partition")
	}
	return fixture
}

func seedTypedOwnershipRepository(
	t *testing.T,
	repositoryDirectory string,
	files map[string][]byte,
) string {
	t.Helper()
	if err := os.MkdirAll(repositoryDirectory, 0o700); err != nil {
		t.Fatal(err)
	}
	runTypedOwnershipGit(t, repositoryDirectory, "init", "-q")
	runTypedOwnershipGit(t, repositoryDirectory, "config", "user.email", "typed-ownership@example.invalid")
	runTypedOwnershipGit(t, repositoryDirectory, "config", "user.name", "Typed Ownership Test")
	paths := make([]string, 0, len(files))
	for path, content := range files {
		if err := os.WriteFile(filepath.Join(repositoryDirectory, path), content, 0o600); err != nil {
			t.Fatal(err)
		}
		paths = append(paths, path)
	}
	sort.Strings(paths)
	runTypedOwnershipGit(t, repositoryDirectory, append([]string{"add", "--"}, paths...)...)
	runTypedOwnershipGit(t, repositoryDirectory, "commit", "-q", "-m", "fixture")
	return runTypedOwnershipGit(t, repositoryDirectory, "rev-parse", "HEAD")
}

func runTypedOwnershipGit(t *testing.T, directory string, args ...string) string {
	t.Helper()
	command := exec.Command("git", args...)
	command.Dir = directory
	output, err := command.CombinedOutput()
	if err != nil {
		t.Fatalf("git %v: %v\n%s", args, err, output)
	}
	return strings.TrimSpace(string(output))
}

// typedOwnershipIndex builds the partial SCIP input: the generated document
// defines SayHello, and the caller document references SayHello only.
// SayHelloAgain stays unindexed so the typed partition's syntax fallback must
// own it — proven-overlap suppression is per-span, not per-partition.
func typedOwnershipIndex(t *testing.T) []byte {
	t.Helper()
	definition := &scip.Occurrence{
		Symbol:      "scip-go . " + typedOwnershipModule + " GreeterClient#SayHello().",
		SymbolRoles: int32(scip.SymbolRole_Definition),
	}
	start, end := typedOwnershipIdentifierRange(t, typedOwnershipGenerated, "\tSayHello(", len("\t"))
	definition.SetSourceRange(scip.NewRangeUnchecked(
		typedOwnershipSCIPRange(typedOwnershipGenerated, start, end),
	))
	reference := &scip.Occurrence{
		Symbol:      definition.GetSymbol(),
		SymbolRoles: int32(scip.SymbolRole_ReadAccess),
	}
	start, end = typedOwnershipIdentifierRange(t, typedOwnershipCaller, "client.SayHello(", len("client."))
	reference.SetSourceRange(scip.NewRangeUnchecked(
		typedOwnershipSCIPRange(typedOwnershipCaller, start, end),
	))
	index := &scip.Index{
		Metadata: &scip.Metadata{TextDocumentEncoding: scip.TextEncoding_UTF8},
		Documents: []*scip.Document{
			{
				RelativePath:     "greeter_grpc.pb.go",
				PositionEncoding: scip.PositionEncoding_UTF8CodeUnitOffsetFromLineStart,
				Occurrences:      []*scip.Occurrence{definition},
			},
			{
				RelativePath:     "main.go",
				PositionEncoding: scip.PositionEncoding_UTF8CodeUnitOffsetFromLineStart,
				Occurrences:      []*scip.Occurrence{reference},
			},
		},
	}
	encoded, err := (proto.MarshalOptions{Deterministic: true}).Marshal(index)
	if err != nil {
		t.Fatal(err)
	}
	return encoded
}

// typedOwnershipIdentifierRange finds the first needle and returns the byte
// range of the identifier that begins prefixBytes into the needle (after the
// tab for "\tSayHello(", after "client." for "client.SayHello(").
func typedOwnershipIdentifierRange(
	t *testing.T, content, needle string, prefixBytes int,
) (int, int) {
	t.Helper()
	offset := strings.Index(content, needle)
	if offset < 0 {
		t.Fatalf("needle %q not found", needle)
	}
	start := offset + prefixBytes
	end := start
	for end < len(content) && typedOwnershipIdentifierByte(content[end]) {
		end++
	}
	return start, end
}

func typedOwnershipIdentifierByte(value byte) bool {
	return value == '_' || value >= 'a' && value <= 'z' ||
		value >= 'A' && value <= 'Z' || value >= '0' && value <= '9'
}

func typedOwnershipSCIPRange(content string, startByte, endByte int) []int32 {
	line := int32(strings.Count(content[:startByte], "\n"))
	lineStart := strings.LastIndexByte(content[:startByte], '\n') + 1
	endLine := int32(strings.Count(content[:endByte], "\n"))
	endLineStart := strings.LastIndexByte(content[:endByte], '\n') + 1
	return []int32{
		line, int32(startByte - lineStart),
		endLine, int32(endByte - endLineStart),
	}
}

// newTypedOwnershipRun begins one partitioned run per scenario, exactly as the
// production reconciler begins one run per domain.
func newTypedOwnershipRun(
	t *testing.T,
	recorder *stagedRecorder,
	fixture typedOwnershipFixture,
) *store.ExtractionRun {
	t.Helper()
	run, err := recorder.BeginPartitionedExtractionRun(t.Context(), store.ExtractionScope{
		Repository: fixture.repository, Commit: fixture.commit,
		UnitDigest: fixture.unitDigest, Domain: typedOwnershipDomain,
	}, fixture.plan.ExtractorVersion, fixture.plan.Digest,
		fixture.plan.CandidateManifestDigest, fixture.plan.Schema,
		store.PartitionedExtractionRunLimits{
			Facts: fixture.plan.Reserved.Facts, Rows: fixture.plan.Reserved.Rows,
			References: fixture.plan.Reserved.References,
		})
	if err != nil {
		t.Fatal(err)
	}
	return run
}

func newTypedOwnershipExecutor(recorder *stagedRecorder) *extract.EvidencePartitionExecutor {
	return &extract.EvidencePartitionExecutor{
		Evidence:               recorder,
		Extractors:             []extract.Extractor{gocaller.NewGRPC()},
		StoreAccounting:        false,
		TypedScopeReservations: true,
	}
}

func (fixture typedOwnershipFixture) source() extractionpublication.SparseSource {
	return extractionpublication.SparseSource{
		OpenDomain: func(ctx context.Context, plan candidate.DomainResultPlan) (*candidate.SparseDomain, error) {
			return fixture.sparse.OpenDomain(ctx, plan.Domain, plan.Version)
		},
		OpenCorpus: func(context.Context, candidate.DomainResultPlan) (sdk.Corpus, func(), error) {
			return typedOwnershipCorpus{
				repo: fixture.repository, commit: fixture.commit, files: fixture.files,
			}, func() {}, nil
		},
	}
}

func executeTypedOwnershipPartition(
	t *testing.T,
	recorder *stagedRecorder,
	executor *extract.EvidencePartitionExecutor,
	fixture typedOwnershipFixture,
	runID string,
	ordinal int,
) candidate.PartitionResultSpec {
	t.Helper()
	lease, err := fixture.source().AcquirePartition(t.Context(), fixture.plan, ordinal)
	if err != nil {
		t.Fatalf("acquire partition %d: %v", ordinal, err)
	}
	defer lease.Release()
	recorder.ordinal.Store(int64(ordinal))
	spec, err := executor.ExecutePartition(t.Context(), fixture.plan, ordinal, lease, runID)
	if err != nil {
		t.Fatalf("execute partition %d: %v", ordinal, err)
	}
	return spec
}

func assertTypedOwnershipMemberQuiet(
	t *testing.T, spec candidate.PartitionResultSpec, staged []store.Assertion,
) {
	t.Helper()
	if spec.Totals.Facts != 0 || len(staged) != 0 {
		t.Fatalf("member partition staged %d facts and %d assertions, want nothing: %+v",
			spec.Totals.Facts, len(staged), staged)
	}
}

// assertTypedOwnershipResolutions asserts the staged claims are exactly the
// want set (operation -> resolution lane), each owned once with its truthful
// provenance — the SayHello callsite resolves through scip (indexed) and
// SayHelloAgain through syntax (unindexed), never both lanes on one callsite.
func assertTypedOwnershipResolutions(
	t *testing.T,
	staged []store.Assertion,
	want map[string]string,
) {
	t.Helper()
	if len(staged) != len(want) {
		t.Fatalf("typed partition staged %d assertions, want %d: %+v", len(staged), len(want), staged)
	}
	seen := make(map[string]string, len(staged))
	for _, assertion := range staged {
		resolution := ""
		switch {
		case strings.Contains(assertion.Detail, `"resolution":"scip"`):
			resolution = "scip"
		case strings.Contains(assertion.Detail, `"resolution":"syntax"`):
			resolution = "syntax"
		default:
			t.Fatalf("staged assertion has no caller resolution lane: %+v", assertion)
		}
		if !strings.Contains(assertion.Detail, "greeter_grpc.pb.go") {
			t.Fatalf("staged assertion lost generated-path provenance: %+v", assertion)
		}
		wantResolution, expected := want[assertion.Object]
		if !expected {
			t.Fatalf("staged assertion has unexpected operation %q: %+v", assertion.Object, assertion)
		}
		if prior, duplicate := seen[assertion.Object]; duplicate {
			t.Fatalf("operation %q staged twice across lanes (%s then %s)", assertion.Object, prior, resolution)
		}
		seen[assertion.Object] = resolution
		if resolution != wantResolution {
			t.Fatalf("operation %q resolution = %q, want %q", assertion.Object, resolution, wantResolution)
		}
	}
}

// AC: member → typed then typed → member, each against one fresh run, stage
// cleanly — the member partition owns nothing and the typed partition owns
// both callsites once (scip where indexed, syntax where not).
func TestPartitionedCallerOwnershipSequentialOrders(t *testing.T) {
	if _, err := exec.LookPath("surreal"); err != nil {
		t.Skip("surreal binary not installed")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	defer cancel()
	backing, err := store.OpenLocalMemory(ctx, t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = backing.Close(context.Background()) })
	root := t.TempDir()
	fixture := buildTypedOwnershipFixture(t,
		filepath.Join(root, "repository"), filepath.Join(root, "candidate"),
		filepath.Join(root, "sparse"), true)

	for _, order := range [][]int{
		{fixture.memberOrdinal, fixture.typedOrdinal},
		{fixture.typedOrdinal, fixture.memberOrdinal},
	} {
		recorder := &stagedRecorder{Surreal: backing}
		run := newTypedOwnershipRun(t, recorder, fixture)
		executor := newTypedOwnershipExecutor(recorder)
		specs := make(map[int]candidate.PartitionResultSpec)
		for _, ordinal := range order {
			specs[ordinal] = executeTypedOwnershipPartition(t, recorder, executor, fixture, run.ID, ordinal)
		}
		assertTypedOwnershipMemberQuiet(t, specs[fixture.memberOrdinal], recorder.stagedAsserts(fixture.memberOrdinal))
		typed := specs[fixture.typedOrdinal]
		if typed.Disposition != candidate.PartitionResultSuccess || typed.Totals.Facts != 2 {
			t.Fatalf("typed partition result = %+v, want success with two facts", typed)
		}
		assertTypedOwnershipResolutions(t, recorder.stagedAsserts(fixture.typedOrdinal), map[string]string{
			typedOwnershipOperation:  "scip",
			typedOwnershipOperation2: "syntax",
		})
	}
}

// AC: both partitions execute concurrently against one run; the member stages
// nothing and no interleaving can reproduce the 20261011d attribute collision.
func TestPartitionedCallerOwnershipConcurrent(t *testing.T) {
	if _, err := exec.LookPath("surreal"); err != nil {
		t.Skip("surreal binary not installed")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 90*time.Second)
	defer cancel()
	backing, err := store.OpenLocalMemory(ctx, t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = backing.Close(context.Background()) })
	root := t.TempDir()
	fixture := buildTypedOwnershipFixture(t,
		filepath.Join(root, "repository"), filepath.Join(root, "candidate"),
		filepath.Join(root, "sparse"), true)
	recorder := &stagedRecorder{Surreal: backing}
	run := newTypedOwnershipRun(t, recorder, fixture)
	executor := newTypedOwnershipExecutor(recorder)

	var wait sync.WaitGroup
	errs := make([]error, 2)
	specs := make([]candidate.PartitionResultSpec, 2)
	for index, ordinal := range []int{fixture.memberOrdinal, fixture.typedOrdinal} {
		wait.Add(1)
		go func(index, ordinal int) {
			defer wait.Done()
			lease, err := fixture.source().AcquirePartition(t.Context(), fixture.plan, ordinal)
			if err != nil {
				errs[index] = err
				return
			}
			defer lease.Release()
			recorder.ordinal.Store(int64(ordinal))
			specs[index], errs[index] = executor.ExecutePartition(
				t.Context(), fixture.plan, ordinal, lease, run.ID)
		}(index, ordinal)
	}
	wait.Wait()
	for index, err := range errs {
		if err != nil {
			t.Fatalf("concurrent partition %d: %v", index, err)
		}
	}
	assertTypedOwnershipMemberQuiet(t, specs[0], nil)
	if specs[1].Disposition != candidate.PartitionResultSuccess || specs[1].Totals.Facts != 2 {
		t.Fatalf("concurrent typed partition result = %+v, want success with two facts", specs[1])
	}
	if total := recorder.totalStaged(); total != 2 {
		t.Fatalf("concurrent run staged %d assertions, want exactly the typed partition's two", total)
	}
}

