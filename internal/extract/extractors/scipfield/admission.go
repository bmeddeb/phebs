package scipfield

import (
	"context"
	"errors"
	"fmt"
	"go/ast"
	"go/token"
	"reflect"
	"strconv"
	"strings"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"

	"github.com/bmeddeb/phebs/internal/idlpreflight"
)

// These are declared committed-input properties, not proof that a generator
// executed. Exact source/SCIP blob authority comes from the trusted corpus.
type generatedAdmission struct {
	path   string
	fields map[string]protoField
}

func preflightCommittedProto(ctx context.Context, content string) error {
	return idlpreflight.Validate(ctx, idlpreflight.Protobuf, content)
}

func (a *generatedAdmission) read(ctx context.Context, set *token.FileSet, file *ast.File, content string) error {
	counts := map[string]int{}
	header := content[:set.Position(file.Package).Offset]
	for _, line := range strings.Split(header, "\n") {
		line = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(line), "//"))
		canonical := strings.Join(strings.Fields(line), " ")
		if strings.HasPrefix(canonical, "protoc-gen-go ") && canonical != "protoc-gen-go v1.36.11" ||
			strings.HasPrefix(canonical, "protoc ") && canonical != "protoc v5.27.1" ||
			strings.HasPrefix(canonical, "Code generated ") && canonical != "Code generated by protoc-gen-go. DO NOT EDIT." {
			return errors.New("unsupported committed protobuf generator header")
		}
		for _, expected := range []string{"Code generated by protoc-gen-go. DO NOT EDIT.", "protoc-gen-go v1.36.11", "protoc v5.27.1"} {
			if strings.Join(strings.Fields(line), " ") == expected {
				counts[expected]++
			}
		}
		if source, ok := strings.CutPrefix(line, "source: "); ok {
			counts["source"]++
			a.path = source
		}
	}
	for _, expected := range []string{"Code generated by protoc-gen-go. DO NOT EDIT.", "protoc-gen-go v1.36.11", "protoc v5.27.1", "source"} {
		if counts[expected] != 1 {
			return errors.New("unsupported committed protobuf generator header")
		}
	}
	if validPath(a.path) != nil || !strings.HasSuffix(a.path, ".proto") {
		return errors.New("invalid committed protobuf source header")
	}
	var raw string
	descriptorCount := 0
	open := 0
	for _, decl := range file.Decls {
		if err := ctx.Err(); err != nil {
			return err
		}
		general, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		if general.Tok == token.TYPE {
			for _, spec := range general.Specs {
				typ := spec.(*ast.TypeSpec)
				structure, ok := typ.Type.(*ast.StructType)
				if !ok {
					continue
				}
				for _, field := range structure.Fields.List {
					if field.Tag == nil {
						continue
					}
					tag, err := strconv.Unquote(field.Tag.Value)
					if err != nil {
						return fmt.Errorf("parse committed generated tag: %w", err)
					}
					api := reflect.StructTag(tag).Get("protogen")
					if api == "" {
						continue
					}
					if api != "open.v1" {
						return errors.New("committed protobuf field recipe requires Open API")
					}
					open++
				}
			}
		}
		if general.Tok != token.CONST {
			continue
		}
		for _, spec := range general.Specs {
			value := spec.(*ast.ValueSpec)
			if len(value.Names) != 1 || !strings.HasSuffix(value.Names[0].Name, "_rawDesc") {
				continue
			}
			descriptorCount++
			if descriptorCount != 1 || len(value.Values) != 1 {
				return errors.New("ambiguous committed generated descriptor")
			}
			var err error
			raw, err = descriptorLiteral(ctx, value.Values[0])
			if err != nil {
				return err
			}
		}
	}
	if open == 0 || raw == "" {
		return errors.New("missing committed Open API descriptor")
	}
	var descriptor descriptorpb.FileDescriptorProto
	if err := (proto.UnmarshalOptions{RecursionLimit: idlpreflight.MaxStructuralDepth * 2}).Unmarshal([]byte(raw), &descriptor); err != nil {
		return fmt.Errorf("decode committed generated descriptor: %w", err)
	}
	if descriptor.GetName() != a.path || descriptor.GetSyntax() != "proto3" || len(descriptor.GetExtension()) != 0 {
		return errors.New("unsupported committed generated descriptor source/syntax")
	}
	a.fields = make(map[string]protoField)
	var walk func(string, string, []*descriptorpb.DescriptorProto) error
	walk = func(full, goPrefix string, messages []*descriptorpb.DescriptorProto) error {
		for _, message := range messages {
			if err := ctx.Err(); err != nil {
				return err
			}
			if message.GetOptions().GetMapEntry() {
				continue
			}
			if len(message.GetExtension()) != 0 {
				return errors.New("unsupported committed protobuf extensions")
			}
			name, goName := message.GetName(), goCamelCase(message.GetName())
			if full != "" {
				name = full + "." + name
			}
			if goPrefix != "" {
				goName = goPrefix + "_" + goName
			}
			for _, field := range message.GetField() {
				if field.GetNumber() <= 0 || field.GetName() == "" {
					return errors.New("invalid committed descriptor field")
				}
				key := protoFieldKey(goName, uint64(field.GetNumber()), field.GetName())
				if _, exists := a.fields[key]; exists {
					return errors.New("ambiguous committed descriptor field")
				}
				a.fields[key] = protoField{messageFullName: name, name: field.GetName(), number: uint64(field.GetNumber())}
			}
			if err := walk(name, goName, message.GetNestedType()); err != nil {
				return err
			}
		}
		return nil
	}
	return walk(descriptor.GetPackage(), "", descriptor.GetMessageType())
}

// Iterative literal traversal avoids source-controlled Go expression depth.
func descriptorLiteral(ctx context.Context, root ast.Expr) (string, error) {
	stack := []ast.Expr{root}
	var value strings.Builder
	for len(stack) > 0 {
		if err := ctx.Err(); err != nil {
			return "", err
		}
		node := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		switch n := node.(type) {
		case *ast.BinaryExpr:
			if n.Op != token.ADD {
				return "", errors.New("unsupported committed descriptor expression")
			}
			stack = append(stack, n.Y, n.X)
		case *ast.BasicLit:
			if n.Kind != token.STRING {
				return "", errors.New("unsupported committed descriptor literal")
			}
			part, err := strconv.Unquote(n.Value)
			if err != nil {
				return "", fmt.Errorf("decode committed descriptor literal: %w", err)
			}
			if len(part) > maxGeneratedBytes-value.Len() {
				return "", errors.New("committed descriptor exceeds generated byte limit")
			}
			value.WriteString(part)
		default:
			return "", errors.New("unsupported committed descriptor expression")
		}
	}
	return value.String(), nil
}

func (a *generatedAdmission) confirm(source string, fields map[string]protoField) error {
	if source != a.path || len(fields) != len(a.fields) {
		return errors.New("committed descriptor/source field census differs")
	}
	for key, field := range fields {
		if a.fields[key] != field {
			return errors.New("committed descriptor/source field identity differs")
		}
	}
	return nil
}
