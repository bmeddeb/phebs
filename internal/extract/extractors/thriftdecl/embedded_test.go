// Modelled on cadence's .gen/go/cadence/cadence.go: the IDL is embedded as an
// interpreted string literal, with quotes and newlines escaped.
const embeddedIDL = "// \"Workflow\" service\ninclude \"shared.thrift\"\n\nnamespace java com.example.cadence\n\n" +
	"service WorkflowService {\n  shared.StartResponse StartWorkflowExecution(1: shared.StartRequest request)\n" +
	"  void Ping()\n}\n"

func embeddedModuleSource(idl, sum string) string {
	if sum == "" {
		digest := sha1.Sum([]byte(idl)) //nolint:gosec // thriftrw fingerprint
		sum = hex.EncodeToString(digest[:])
	}
	return "// Code generated by thriftrw v1.34.0. DO NOT EDIT.\n// @generated\n\npackage cadence\n\n" +
		"import thriftreflect \"go.uber.org/thriftrw/thriftreflect\"\n\n" +
		"var ThriftModule = &thriftreflect.ThriftModule{\n\tName:     \"cadence\",\n" +
		"\tPackage:  \"github.com/acme/cadence/.gen/go/cadence\",\n\tFilePath: \"cadence.thrift\",\n" +
		"\tSHA1:     \"" + sum + "\",\n\tRaw:      rawIDL,\n}\n\nconst rawIDL = " + strconv.Quote(idl) + "\n"
}

const embeddedGoPath = ".gen/go/cadence/cadence.go"

// TestEmbeddedIDLDeclaresOperationsCitingTheGoFile is the PHEBS-47 core: with
// no committed .thrift, a digest-valid thriftrw module declares its service
// and operations, with the Go file as subject and lineage, the scope from
// FilePath, and byte spans that cite the Go literal's own bytes.
func TestEmbeddedIDLDeclaresOperationsCitingTheGoFile(t *testing.T) {
	source := embeddedModuleSource(embeddedIDL, "")
	facts, coverage := mustExtract(t, memoryCorpus{
		repo: "github.com/acme/cadence", commit: "c0ffee",
		files: map[string]string{embeddedGoPath: source, ".gen/go/cadence/other.go": "package cadence\n"},
	})
	if coverage.UnresolvedCount != 0 {
		t.Fatalf("unresolved = %d", coverage.UnresolvedCount)
	}
	operation := findPredicateFact(t, facts, "DECLARES_OPERATION", "cadence.WorkflowService/StartWorkflowExecution")
	findPredicateFact(t, facts, "DECLARES_OPERATION", "cadence.WorkflowService/Ping")
	service := findPredicateFact(t, facts, "DECLARES_SERVICE", "cadence.WorkflowService")
	literalLine := strings.Count(source[:strings.Index(source, "const rawIDL")], "\n") + 1
	for _, fact := range []sdk.Fact{operation, service} {
		if fact.Assertion.Subject != embeddedGoPath || fact.Path != embeddedGoPath ||
			fact.Assertion.Tier != "exact" || fact.StartLine != literalLine || fact.EndLine != literalLine {
			t.Fatalf("embedded fact identity = %+v", fact)
		}
		if fact.Atom.StartByte < strings.Index(source, "const rawIDL") || fact.Atom.EndByte > len(source) {
			t.Fatalf("span %d..%d is outside the literal", fact.Atom.StartByte, fact.Atom.EndByte)
		}
	}
	if got := source[service.Atom.StartByte:service.Atom.EndByte]; got != "service WorkflowService {" {
		t.Fatalf("service citation = %q", got)
	}
	if got := source[operation.Atom.StartByte:operation.Atom.EndByte]; !strings.HasPrefix(got, "shared.StartResponse StartWorkflowExecution(") {
		t.Fatalf("operation citation = %q", got)
	}
	if operation.Atom.BlobDigest == "" || operation.Assertion.Lineage == "" {
		t.Fatalf("embedded fact lacks blob or lineage: %+v", operation)
	}
	committed := mustExtractLineage(t, map[string]string{"idl/cadence.thrift": embeddedIDL})
	if committed == operation.Assertion.Lineage {
		t.Fatal("embedded and committed declarations share a lineage")
	}
}

func mustExtractLineage(t *testing.T, files map[string]string) string {
	t.Helper()
	facts, _ := mustExtract(t, memoryCorpus{repo: "github.com/acme/cadence", commit: "c0ffee", files: files})
	return findPredicateFact(t, facts, "DECLARES_OPERATION", "cadence.WorkflowService/Ping").Assertion.Lineage
}

func TestEmbeddedIDLDefersToCommittedThrift(t *testing.T) {
	for name, committedPath := range map[string]string{
		"same name at the root": "cadence.thrift",
		"same name nested":      "idls/thrift/cadence.thrift",
	} {
		t.Run(name, func(t *testing.T) {
			// The committed file differs: it still governs, and the embedded
			// module contributes nothing.
			facts, _ := mustExtract(t, memoryCorpus{
				repo: "github.com/acme/cadence", commit: "c0ffee",
				files: map[string]string{
					embeddedGoPath: embeddedModuleSource(embeddedIDL, ""),
					committedPath:  "service Other {\n  void Only()\n}\n",
				},
			})
			for _, fact := range facts {
				if fact.Path == embeddedGoPath {
					t.Fatalf("embedded IDL declared despite a committed file: %+v", fact.Assertion)
				}
			}
		})
	}
}

func TestEmbeddedIDLDigestMismatchIsAGap(t *testing.T) {
	facts, coverage := mustExtract(t, memoryCorpus{
		repo: "github.com/acme/cadence", commit: "c0ffee",
		files: map[string]string{embeddedGoPath: embeddedModuleSource(embeddedIDL, strings.Repeat("0", 40))},
	})
	if coverage.UnresolvedCount != 1 || len(facts) != 1 ||
		facts[0].Assertion.Predicate != "THRIFT_EXTRACTION_GAP" ||
		facts[0].Assertion.Object != "embedded_idl_digest_mismatch" || facts[0].Path != embeddedGoPath {
		t.Fatalf("digest mismatch facts = %+v (unresolved %d)", facts, coverage.UnresolvedCount)
	}
}

func TestEmbeddedModuleCandidateAgreesWithCandidatePolicy(t *testing.T) {
	for _, filePath := range []string{
		".gen/go/cadence/cadence.go", "echo/echo.go", "a/b/kv/kv.go",
		"echo/client.go", "echo/echo_test.go", "echo.go", "api.thrift", "kv/kv.thrift",
	} {
		if thriftdecl.IsEmbeddedModuleCandidate(filePath) != extract.ThriftRWModuleCandidatePath(filePath) {
			t.Fatalf("candidate predicates disagree on %q", filePath)
		}
	}
	if !thriftdecl.New().Candidate(".gen/go/cadence/cadence.go") || thriftdecl.New().Candidate("echo/client.go") {
		t.Fatal("thriftdecl Candidate does not admit exactly the module pre-filter")
	}
}
