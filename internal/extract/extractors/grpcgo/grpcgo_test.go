func TestPackageLessServiceResolves(t *testing.T) {
	stub := `// Code generated by protoc-gen-go-grpc. DO NOT EDIT.
package greeter

const Greeter_SayHello_FullMethodName = "/Greeter/SayHello"
var Greeter_ServiceDesc = grpc.ServiceDesc{ServiceName: "Greeter"}
func RegisterGreeterServer(s grpc.ServiceRegistrar, srv GreeterServer) {}
`
	consumer := `package main
func run(ctx context.Context, client greeter.GreeterClient, s grpc.ServiceRegistrar) {
	client.SayHello(ctx, req)
	greeter.RegisterGreeterServer(s, &impl{})
}
`
	corpus := memoryCorpus{repo: "example.com/app", commit: "c0ffee", files: map[string]string{
		"api/greeter_grpc.pb.go": stub,
		"cmd/app/main.go":        consumer,
	}}
	facts, cov := collect(t, corpus)
	if cov.UnresolvedCount != 0 {
		t.Fatalf("package-less service unresolved = %d", cov.UnresolvedCount)
	}
	got := map[string]bool{}
	for _, fact := range facts {
		got[fact.Assertion.Predicate+" "+fact.Assertion.Object] = true
		if fact.Assertion.Lineage == "" {
			t.Fatalf("package-less fact has no lineage: %+v", fact)
		}
	}
	for _, want := range []string{
		"CALLS_OPERATION /Greeter/SayHello",
		"REGISTERS_GRPC_SERVICE Greeter",
	} {
		if !got[want] {
			t.Fatalf("missing package-less fact %q; got %v", want, got)
		}
	}
}

func TestNoAccuracyLanguageInOutputs(t *testing.T) {
	facts, cov := collect(t, fixtureCorpus())
	blob, _ := json.Marshal(facts)
	all := strings.ToLower(string(blob) + strings.Join(cov.Protocols, " "))
	for _, banned := range []string{"accuracy", "precision", "recall", "validated"} {
		if strings.Contains(all, banned) {
			t.Fatalf("output contains accuracy-claim language %q", banned)
		}
	}
}

func keys(m map[string]sdk.Fact) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
