func collect(t *testing.T, corpus memoryCorpus) ([]sdk.Fact, sdk.Coverage) {
	t.Helper()
	var facts []sdk.Fact
	ctx := sdk.WithDiagnosticCounters(context.Background())
	cov, err := New().Extract(ctx, corpus, func(f sdk.Fact) error {
		facts = append(facts, f)
		return nil
	})
	if err != nil {
		t.Fatalf("extract: %v", err)
	}
	return facts, cov
}

func TestExtractResolvesCallsRegistrationsAndAbstains(t *testing.T) {
	facts, cov := collect(t, fixtureCorpus())
	if diagnosticValue(cov, "generated_stubs_recognized") != 2 ||
		diagnosticValue(cov, "first_pass_reads") != 2 ||
		diagnosticValue(cov, "second_pass_reads") != 2 ||
		diagnosticValue(cov, "registrations_found") != 1 ||
		diagnosticValue(cov, "call_sites_found") != 2 ||
		diagnosticValue(cov, "ambiguous_calls") == 0 {
		t.Fatalf("diagnostics = %+v", cov.Diagnostics)
	}

	got := map[string]sdk.Fact{}
	for _, f := range facts {
		got[f.Assertion.Predicate+" "+f.Assertion.Object] = f
	}
	call, ok := got["CALLS_OPERATION /helloworld.Greeter/SayAgain"]
	if !ok {
		t.Fatalf("missing unique call-site fact; got %v", keys(got))
	}
	if call.Assertion.Tier != "heuristic" || call.Assertion.CodeRole != "production" {
		t.Fatalf("call tier/role = %q/%q", call.Assertion.Tier, call.Assertion.CodeRole)
	}
	if !strings.HasPrefix(call.Assertion.Lineage, "provisional_repo_path_v1_") {
		t.Fatalf("call lineage = %q", call.Assertion.Lineage)
	}
	if _, ok := got["CALLS_OPERATION /acme.billing.Billing/Charge"]; !ok {
		t.Fatalf("missing billing call fact")
	}
	reg, ok := got["REGISTERS_GRPC_SERVICE helloworld.Greeter"]
	if !ok {
		t.Fatalf("missing registration fact")
	}
	if reg.Assertion.Tier != "derived" {
		t.Fatalf("registration tier = %q", reg.Assertion.Tier)
	}
	// SayHello is declared by two services: syntactic resolution abstains.
	for key := range got {
		if strings.HasPrefix(key, "CALLS_OPERATION ") && strings.Contains(key, "SayHello") {
			t.Fatalf("ambiguous positive method emitted: %s", key)
		}
	}
	gap, ok := got["UNRESOLVED_GRPC_CALL SayHello"]
	if !ok || gap.Assertion.Tier != "unresolved" ||
		!strings.Contains(gap.Assertion.Detail, `"candidate_count":2`) {
		t.Fatalf("ambiguous call gap = %+v", gap)
	}
	if cov.UnresolvedCount != 1 {
		t.Fatalf("unresolved = %d, want 1 (ambiguous SayHello)", cov.UnresolvedCount)
	}
	// Frobnicate is not in any stub index: silently out of domain, not unresolved.
	for _, f := range facts {
		var detail map[string]any
		if err := json.Unmarshal([]byte(f.Assertion.Detail), &detail); err != nil {
			t.Fatalf("detail is not valid JSON: %q", f.Assertion.Detail)
		}
	}
}

func diagnosticValue(coverage sdk.Coverage, name string) int64 {
	for _, counter := range coverage.Diagnostics {
		if counter.Name == name {
			return counter.Value
		}
	}
	return -1
}

