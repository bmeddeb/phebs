// These versions attest the complete selected generator set on the existing
// shared domain. Changing the set invalidates reuse and every stable reader.
const (
	CommittedApacheVersion         = "1.4.0-released.apache.1"
	CommittedThriftRWVersion       = "1.4.0-released.thriftrw.1"
	CommittedApacheThriftRWVersion = "1.4.0-released.apache-thriftrw.1"
)

type generatorSelection uint8

const (
	apacheGenerator generatorSelection = 1 << iota
	thriftRWGenerator
)

// NewCommittedApache admits only header-declared Apache Thrift0.14.1 input.
func NewCommittedApache() sdk.Extractor { return extractor{selected: apacheGenerator} }

// NewCommittedThriftRW admits only digest-bound, header-declared thriftrw1.34.0 input.
func NewCommittedThriftRW() sdk.Extractor { return extractor{selected: thriftRWGenerator} }

// NewCommittedApacheThriftRW admits both fixed recipes in one extraction pass.
func NewCommittedApacheThriftRW() sdk.Extractor {
	return extractor{selected: apacheGenerator | thriftRWGenerator}
}

func hasThriftRWGeneratedMarker(content string) bool {
	if len(content) > 4096 {
		content = content[:4096]
	}
	for _, line := range strings.Split(content, "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "// Code generated by thriftrw") {
			return true
		}
	}
	return false
}

// Headers declare committed-input properties; they do not prove execution of
// a compiler. Unselected generator files cannot contribute bindings. All
// admission happens before the existing emission pass begins.
func admitGeneratedHeader(ctx context.Context, path, content string, selected generatorSelection) (generatorSelection, error) {
	if err := ctx.Err(); err != nil {
		return 0, err
	}
	file, err := parser.ParseFile(token.NewFileSet(), path, content, parser.PackageClauseOnly|parser.ParseComments)
	if err != nil {
		return 0, err
	}
	var apacheHeader, rwHeader string
	var apacheCount, rwCount int
	for index, group := range file.Comments {
		if index&4095 == 0 {
			if err := ctx.Err(); err != nil {
				return 0, err
			}
		}
		for _, comment := range group.List {
			if comment.Pos() >= file.Package {
				continue
			}
			line := strings.Join(strings.Fields(comment.Text), " ")
			switch {
			case strings.HasPrefix(line, "// Code generated by Thrift Compiler"), strings.HasPrefix(line, "// Autogenerated by Thrift Compiler"):
				apacheHeader = line
				apacheCount++
			case strings.HasPrefix(line, "// Code generated by thriftrw"):
				rwHeader = line
				rwCount++
			}
		}
	}
	if apacheCount > 0 && rwCount > 0 {
		return 0, errors.New("ambiguous committed Thrift generator headers")
	}
	if apacheCount > 0 {
		if selected&apacheGenerator == 0 {
			return 0, nil
		}
		if apacheCount != 1 || apacheHeader != "// Code generated by Thrift Compiler (0.14.1). DO NOT EDIT." || looksLikeThriftRWModule(content) {
			return 0, errors.New("unsupported committed Apache Thrift generator header")
		}
		return apacheGenerator, nil
	}
	if selected&thriftRWGenerator == 0 {
		return 0, nil
	}
	if rwCount != 1 || rwHeader != "// Code generated by thriftrw v1.34.0. DO NOT EDIT." || !looksLikeThriftRWModule(content) {
		return 0, errors.New("unsupported committed thriftrw generator header/module")
	}
	return thriftRWGenerator, nil
}

func admitDefinitionSymbol(definition generatedDefinition) error {
	symbol, err := scip.ParseSymbol(definition.symbol)
	if err != nil || symbol.GetScheme() != "scip-go" || symbol.GetPackage().GetManager() != "gomod" || symbol.GetPackage().GetName() == "" || symbol.GetPackage().GetVersion() == "" {
		return errors.New("unsupported committed Thrift SCIP symbol package")
	}
	suffix := scip.Descriptor_Term
	if definition.field.accessor {
		suffix = scip.Descriptor_Method
	}
	descriptors := symbol.GetDescriptors()
	if len(descriptors) < 2 || descriptors[len(descriptors)-1].GetSuffix() != suffix || descriptors[len(descriptors)-1].GetName() != definition.identifier || descriptors[len(descriptors)-2].GetSuffix() != scip.Descriptor_Type || descriptors[len(descriptors)-2].GetName() != definition.field.message {
		return errors.New("unsupported committed Thrift SCIP field/accessor shape")
	}
	return nil
}
