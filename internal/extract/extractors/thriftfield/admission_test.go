func committedMixedCorpus(t *testing.T) memoryCorpus {
	t.Helper()
	c := fixtureCorpus(t, "v1.0.0", "old_name", "OldName", 10)
	index := decodeIndex(t, c.files[indexPath])
	const rwHeader = "// Code generated by thriftrw v1.34.0. DO NOT EDIT.\n"
	c.files["generated/shared.go"] = rwHeader + c.files["generated/shared.go"]
	for _, occurrence := range index.Documents[0].Occurrences {
		r, ok := occurrence.SourceRange()
		if !ok {
			t.Fatal("fixture has no range")
		}
		r.Start.Line++
		r.End.Line++
		occurrence.Range = nil //nolint:staticcheck // Clear legacy fixture coordinates before replacing them with typed ranges.
		occurrence.TypedRange = r.AsTypedRange()
	}
	const apache = "// Code generated by Thrift Compiler (0.14.1). DO NOT EDIT.\npackage apache\ntype Result struct { Success any `thrift:\"success,0,optional\"` }\n"
	const use = "package use\nfunc use(v *apache.Result) { _ = v.Success }\n"
	const symbol = "scip-go gomod example.com/apache v1.0.0 gen/Result#Success."
	c.files["apache/generated.go"], c.files["apache/use.go"] = apache, use
	index.Metadata = &scip.Metadata{ToolInfo: &scip.ToolInfo{Name: "scip-go", Version: "0.2.7"}, TextDocumentEncoding: scip.TextEncoding_UTF8}
	index.Documents = append(index.Documents,
		&scip.Document{RelativePath: "apache/generated.go", PositionEncoding: scip.PositionEncoding_UTF8CodeUnitOffsetFromLineStart, Occurrences: []*scip.Occurrence{{Range: rangeFor(t, apache, "Success", 0, scip.PositionEncoding_UTF8CodeUnitOffsetFromLineStart), Symbol: symbol, SymbolRoles: int32(scip.SymbolRole_Definition)}}},
		&scip.Document{RelativePath: "apache/use.go", PositionEncoding: scip.PositionEncoding_UTF8CodeUnitOffsetFromLineStart, Occurrences: []*scip.Occurrence{{Range: rangeFor(t, use, "Success", 0, scip.PositionEncoding_UTF8CodeUnitOffsetFromLineStart), Symbol: symbol, SymbolRoles: int32(scip.SymbolRole_ReadAccess)}}},
	)
	c.files[indexPath] = encodeIndex(t, index)
	return c
}

func TestCommittedThriftGeneratorSelection(t *testing.T) {
	for _, test := range []struct {
		name, version string
		reader        sdk.Extractor
		apache, rw    int
	}{
		{"historical", "1.4.0", New(), 1, 2},
		{"Apache only", CommittedApacheVersion, NewCommittedApache(), 1, 0},
		{"thriftrw only", CommittedThriftRWVersion, NewCommittedThriftRW(), 0, 2},
		{"both", CommittedApacheThriftRWVersion, NewCommittedApacheThriftRW(), 1, 2},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := committedMixedCorpus(t)
			c.reads = map[string]int{}
			apache, rw := 0, 0
			coverage, err := test.reader.Extract(t.Context(), c, func(f sdk.Fact) error {
				switch {
				case strings.Contains(f.Assertion.Detail, `"generator":"apache"`):
					apache++
					if f.Assertion.Tier != "derived" || !strings.Contains(f.Assertion.Detail, `"source_binding":"none"`) || f.Assertion.Object != "apache.Result#0" {
						t.Fatalf("Apache identity/tier changed: %+v", f)
					}
				case strings.Contains(f.Assertion.Detail, `"generator":"thriftrw"`):
					rw++
					if f.Assertion.Tier != "exact" || !strings.Contains(f.Assertion.Detail, `"source_binding":"module_digest"`) {
						t.Fatalf("thriftrw identity/tier changed: %+v", f)
					}
				default:
					t.Fatal("unknown generator emitted")
				}
				return nil
			})
			if err != nil || test.reader.Version() != test.version || apache != test.apache || rw != test.rw {
				t.Fatalf("version=%s Apache=%d RW=%d coverage=%+v err=%v", test.reader.Version(), apache, rw, coverage, err)
			}
			if test.name == "Apache only" && strings.Contains(strings.Join(coverage.Protocols, ","), "thriftrw") || test.name == "thriftrw only" && strings.Contains(strings.Join(coverage.Protocols, ","), "apache") {
				t.Fatal("coverage names unselected generator")
			}
			if c.reads[indexPath] != 1 {
				t.Fatalf("composed reader parsed input %d times", c.reads[indexPath])
			}
		})
	}
}

func TestCommittedThriftAdmissionRefusesAtomically(t *testing.T) {
	for _, test := range []struct {
		name   string
		mutate func(*memoryCorpus)
	}{
		{"wrong root path", func(c *memoryCorpus) { c.typedPath = "typed/index.scip"; c.files[c.typedPath] = c.files[indexPath] }},
		{"wrong Apache version", func(c *memoryCorpus) {
			c.files["apache/generated.go"] = strings.Replace(c.files["apache/generated.go"], "0.14.1", "0.14.2", 1)
		}},
		{"wrong thriftrw version", func(c *memoryCorpus) {
			c.files["generated/shared.go"] = strings.Replace(c.files["generated/shared.go"], "v1.34.0", "v1.35.0", 1)
		}},
		{"missing RW header", func(c *memoryCorpus) {
			c.files["generated/shared.go"] = strings.Replace(c.files["generated/shared.go"], "// Code generated by thriftrw v1.34.0. DO NOT EDIT.\n", "", 1)
		}},
		{"missing RW module", func(c *memoryCorpus) {
			c.files["generated/shared.go"] = strings.ReplaceAll(c.files["generated/shared.go"], "ThriftModule", "OtherModule")
		}},
		{"duplicate header", func(c *memoryCorpus) {
			c.files["apache/generated.go"] = "// Code generated by Thrift Compiler (0.14.1). DO NOT EDIT.\n" + c.files["apache/generated.go"]
		}},
		{"contradictory headers", func(c *memoryCorpus) {
			c.files["generated/shared.go"] = "// Code generated by Thrift Compiler (0.14.1). DO NOT EDIT.\n" + c.files["generated/shared.go"]
		}},
		{"invalid module digest", func(c *memoryCorpus) {
			source := c.files["generated/shared.go"]
			start := strings.Index(source, "SHA1: \"") + len("SHA1: \"")
			if start < len("SHA1: \"") {
				t.Fatal("fixture has no SHA1 literal")
			}
			replacement := "0"
			if source[start] == '0' {
				replacement = "1"
			}
			c.files["generated/shared.go"] = source[:start] + replacement + source[start+1:]
		}},
		{"foreign symbol package", func(c *memoryCorpus) {
			i := decodeIndex(t, c.files[indexPath])
			for _, doc := range i.Documents {
				for _, occurrence := range doc.Occurrences {
					occurrence.Symbol = strings.ReplaceAll(occurrence.Symbol, "scip-go gomod ", "another gomod ")
				}
			}
			c.files[indexPath] = encodeIndex(t, i)
		}},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := committedMixedCorpus(t)
			before := strings.Join([]string{c.files[indexPath], c.files["apache/generated.go"], c.files["generated/shared.go"], c.typedPath}, "\x00")
			test.mutate(&c)
			after := strings.Join([]string{c.files[indexPath], c.files["apache/generated.go"], c.files["generated/shared.go"], c.typedPath}, "\x00")
			if before == after {
				t.Fatal("mutation did not change the input")
			}
			emitted := 0
			_, err := NewCommittedApacheThriftRW().Extract(t.Context(), c, func(sdk.Fact) error { emitted++; return nil })
			if err == nil || emitted != 0 {
				t.Fatalf("unadmitted input emitted=%d err=%v", emitted, err)
			}
		})
	}
	for _, test := range []struct {
		name   string
		change func(*scip.Index)
	}{
		{"indexer", func(i *scip.Index) { i.Metadata.ToolInfo.Version = "0.2.8" }},
		{"metadata encoding", func(i *scip.Index) { i.Metadata.TextDocumentEncoding = scip.TextEncoding_UTF16 }},
		{"document encoding", func(i *scip.Index) {
			i.Documents[0].PositionEncoding = scip.PositionEncoding_UTF16CodeUnitOffsetFromLineStart
		}},
		{"field suffix", func(i *scip.Index) {
			for _, d := range i.Documents {
				for _, o := range d.Occurrences {
					o.Symbol = strings.ReplaceAll(o.Symbol, "#Success.", "#Success().")
				}
			}
		}},
	} {
		t.Run(test.name, func(t *testing.T) {
			c := committedMixedCorpus(t)
			i := decodeIndex(t, c.files[indexPath])
			test.change(i)
			c.files[indexPath] = encodeIndex(t, i)
			emitted := 0
			_, err := NewCommittedApacheThriftRW().Extract(t.Context(), c, func(sdk.Fact) error { emitted++; return nil })
			if err == nil || emitted != 0 {
				t.Fatalf("emitted=%d err=%v", emitted, err)
			}
		})
	}
}

func TestCommittedThriftMissingIndexAndUnselectedGenerator(t *testing.T) {
	c := committedMixedCorpus(t)
	delete(c.files, indexPath)
	coverage, err := NewCommittedApacheThriftRW().Extract(t.Context(), c, func(sdk.Fact) error { t.Fatal("missing input emitted"); return nil })
	if err != nil || len(coverage.Protocols) != 1 || coverage.Protocols[0] != "scip-index-absent" {
		t.Fatalf("coverage=%+v err=%v", coverage, err)
	}
	c = committedMixedCorpus(t)
	c.files["generated/shared.go"] = strings.Replace(c.files["generated/shared.go"], "v1.34.0", "v9.0.0", 1) + "\ninvalid unselected body"
	count := 0
	_, err = NewCommittedApache().Extract(t.Context(), c, func(sdk.Fact) error { count++; return nil })
	if err != nil || count != 1 {
		t.Fatalf("unselected generator affected Apache count=%d err=%v", count, err)
	}
}
