// PHEBS-46: thriftrw + thriftrw-plugin-yarpc generated Go clients. The
// relation from a client to its .thrift declaration is not derived here; the
// resolver catalog proves it from the parent module's embedded provenance
// (ThriftModule.Package, FilePath and SHA1) before any symbol is admitted.

const thriftRWYARPCHeader = "// Code generated by thriftrw-plugin-yarpc"

var (
	thriftRWModuleHeader = regexp.MustCompile(`^// Code generated by thriftrw v[0-9]+\.[0-9]+\.[0-9]+[^\n]*\. DO NOT EDIT\.`)
	thriftRWSHA1         = regexp.MustCompile(`^[0-9a-f]{40}$`)
)

// ThriftRWModule is the provenance a thriftrw-generated package embeds for the
// one .thrift file it was generated from, plus the wire spelling of every
// service method declared there.
type ThriftRWModule struct {
	Name     string
	Package  string
	FilePath string
	SHA1     string
	// MethodNames maps a generated "<Service>_<Method>_Args" type to the
	// Thrift method name its MethodName() returns.
	MethodNames map[string]string
}

// IsThriftRWYARPCClient reports whether content starts with the exact
// thriftrw-plugin-yarpc generated-code header line.
func IsThriftRWYARPCClient(content string) bool {
	line, _, _ := strings.Cut(firstBytes(content, 256), "\n")
	return strings.TrimRight(line, "\r") == thriftRWYARPCHeader
}

// IsThriftRWModuleSource reports whether content starts with a thriftrw
// generated-code header ("// Code generated by thriftrw vX.Y.Z. DO NOT EDIT.").
func IsThriftRWModuleSource(content string) bool {
	return thriftRWModuleHeader.MatchString(firstBytes(content, 256))
}

// ParseThriftRWModule extracts the embedded ThriftModule provenance and the
// MethodName() spellings from one thriftrw-generated Go file. ok is false when
// the file is not a thriftrw module source or declares no ThriftModule.
func ParseThriftRWModule(filePath, content string) (module ThriftRWModule, ok bool, err error) {
	if len(content) > maxGeneratedBytes {
		return ThriftRWModule{}, false, errors.New("thriftrw module source exceeds syntax bound")
	}
	if !utf8.ValidString(content) || !IsThriftRWModuleSource(content) {
		return ThriftRWModule{}, false, nil
	}
	file, err := parser.ParseFile(token.NewFileSet(), filePath, content, parser.SkipObjectResolution)
	if err != nil {
		return ThriftRWModule{}, false, err
	}
	found := false
	module.MethodNames = make(map[string]string)
	for _, declaration := range file.Decls {
		switch value := declaration.(type) {
		case *ast.GenDecl:
			if value.Tok != token.VAR {
				continue
			}
			for _, spec := range value.Specs {
				fields, isModule := thriftModuleLiteral(spec)
				if !isModule {
					continue
				}
				if found {
					return ThriftRWModule{}, false, errors.New("thriftrw source declares ThriftModule twice")
				}
				found = true
				module.Name, module.Package = fields["Name"], fields["Package"]
				module.FilePath, module.SHA1 = fields["FilePath"], fields["SHA1"]
			}
		case *ast.FuncDecl:
			if receiver, name, isMethodName := methodNameFunc(value); isMethodName {
				if prior, duplicate := module.MethodNames[receiver]; duplicate && prior != name {
					return ThriftRWModule{}, false, errors.New("thriftrw MethodName is declared twice")
				}
				module.MethodNames[receiver] = name
			}
		}
	}
	if !found {
		return ThriftRWModule{}, false, nil
	}
	if module.Name == "" || module.Package == "" || module.FilePath == "" ||
		!strings.HasSuffix(module.FilePath, ".thrift") || !thriftRWSHA1.MatchString(module.SHA1) {
		return ThriftRWModule{}, false, errors.New("thriftrw ThriftModule provenance is incomplete")
	}
	return module, true, nil
}

// thriftModuleLiteral matches `ThriftModule = &thriftreflect.ThriftModule{...}`
// and returns its string-literal fields.
func thriftModuleLiteral(spec ast.Spec) (map[string]string, bool) {
	valueSpec, ok := spec.(*ast.ValueSpec)
	if !ok || len(valueSpec.Names) != 1 || valueSpec.Names[0].Name != "ThriftModule" ||
		len(valueSpec.Values) != 1 {
		return nil, false
	}
	unary, ok := valueSpec.Values[0].(*ast.UnaryExpr)
	if !ok || unary.Op != token.AND {
		return nil, false
	}
	literal, ok := unary.X.(*ast.CompositeLit)
	if !ok {
		return nil, false
	}
	selector, ok := literal.Type.(*ast.SelectorExpr)
	if !ok || selector.Sel.Name != "ThriftModule" {
		return nil, false
	}
	fields := make(map[string]string)
	for _, element := range literal.Elts {
		pair, ok := element.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		key, ok := pair.Key.(*ast.Ident)
		if !ok {
			continue
		}
		if text, isString := stringLiteral(pair.Value); isString {
			fields[key.Name] = text
		}
	}
	return fields, true
}

// methodNameFunc matches `func (v *T_Args) MethodName() string { return "x" }`.
func methodNameFunc(fn *ast.FuncDecl) (receiver, name string, ok bool) {
	if fn.Name.Name != "MethodName" || fn.Recv == nil || len(fn.Recv.List) != 1 ||
		fn.Body == nil || len(fn.Body.List) != 1 || fn.Type.Params.NumFields() != 0 {
		return "", "", false
	}
	receiver = receiverTypeName(fn.Recv.List[0].Type)
	if !strings.HasSuffix(receiver, "_Args") {
		return "", "", false
	}
	statement, isReturn := fn.Body.List[0].(*ast.ReturnStmt)
	if !isReturn || len(statement.Results) != 1 {
		return "", "", false
	}
	name, ok = stringLiteral(statement.Results[0])
	if !ok || name == "" {
		return "", "", false
	}
	return receiver, name, true
}

func stringLiteral(expression ast.Expr) (string, bool) {
	literal, ok := expression.(*ast.BasicLit)
	if !ok || literal.Kind != token.STRING {
		return "", false
	}
	value, err := strconv.Unquote(literal.Value)
	return value, err == nil
}

// YARPCClientModuleImport returns the import path of the thriftrw package a
// YARPC client builds its arguments with: the one package every
// `<alias>.<Service>_<Method>_Helper.Args(...)` call goes through. A client
// also imports thriftrw packages for shared types only, so the import list
// alone does not name the parent. ok is false when no method uses a helper or
// helpers go through more than one package.
func YARPCClientModuleImport(filePath, content string) (importPath string, ok bool, err error) {
	if len(content) > maxGeneratedBytes || !utf8.ValidString(content) || !IsThriftRWYARPCClient(content) {
		return "", false, errors.New("not a thriftrw-plugin-yarpc client source")
	}
	file, err := parser.ParseFile(token.NewFileSet(), filePath, content, parser.SkipObjectResolution)
	if err != nil {
		return "", false, err
	}
	aliases := make(map[string]string)
	for _, spec := range file.Imports {
		value, unquoteErr := strconv.Unquote(spec.Path.Value)
		if unquoteErr == nil && spec.Name != nil {
			aliases[spec.Name.Name] = value
		}
	}
	used := make(map[string]struct{})
	for _, declaration := range file.Decls {
		fn, isFunc := declaration.(*ast.FuncDecl)
		if !isFunc || fn.Recv == nil || fn.Body == nil {
			continue
		}
		ast.Inspect(fn.Body, func(node ast.Node) bool {
			call, isCall := node.(*ast.CallExpr)
			if !isCall {
				return true
			}
			args, isSelector := call.Fun.(*ast.SelectorExpr)
			if !isSelector || args.Sel.Name != "Args" {
				return true
			}
			helper, isSelector := args.X.(*ast.SelectorExpr)
			if !isSelector || !strings.HasSuffix(helper.Sel.Name, "_Helper") {
				return true
			}
			if pkg, isIdent := helper.X.(*ast.Ident); isIdent {
				used[pkg.Name] = struct{}{}
			}
			return true
		})
	}
	if len(used) != 1 {
		return "", false, nil
	}
	for alias := range used {
		importPath, ok = aliases[alias]
	}
	return importPath, ok, nil
}

// DescribeThriftRWYARPCClient returns the generated symbols of one YARPC
// client: each Interface method whose implementation passes exactly one
// "<parent>.<Service>_<Method>_Helper.Args" value, spelled with the parent
// module's MethodName() literal and the `thrift.Config{Service: …}` literal of
// New. Methods that cannot be tied to one wire name are omitted, so their
// calls stay unresolved.
func DescribeThriftRWYARPCClient(
	generatedPath, importPath, parentImport, content string,
	module ThriftRWModule,
) ([]GeneratedSymbol, error) {
	if generatedPath == "" {
		return nil, errors.New("generated path is required")
	}
	if len(content) > maxGeneratedBytes || !utf8.ValidString(content) || !IsThriftRWYARPCClient(content) {
		return nil, errors.New("not a thriftrw-plugin-yarpc client source")
	}
	file, err := parser.ParseFile(token.NewFileSet(), generatedPath, content, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	parentAlias := ""
	for _, spec := range file.Imports {
		value, unquoteErr := strconv.Unquote(spec.Path.Value)
		if unquoteErr != nil || value != parentImport {
			continue
		}
		if spec.Name == nil {
			return nil, errors.New("YARPC client imports its thriftrw module without a name")
		}
		parentAlias = spec.Name.Name
	}
	if parentAlias == "" || parentAlias == "_" || parentAlias == "." {
		return nil, errors.New("YARPC client does not import its thriftrw module")
	}
	interfaceMethods := yarpcInterfaceMethods(file)
	service, constructor := yarpcService(file)
	if service == "" || len(interfaceMethods) == 0 {
		return nil, nil
	}
	var result []GeneratedSymbol
	for _, declaration := range file.Decls {
		fn, ok := declaration.(*ast.FuncDecl)
		if !ok || fn.Recv == nil || len(fn.Recv.List) != 1 || fn.Body == nil ||
			receiverTypeName(fn.Recv.List[0].Type) != "client" {
			continue
		}
		if _, exported := interfaceMethods[fn.Name.Name]; !exported {
			continue
		}
		helpers := yarpcHelperArgs(fn, parentAlias)
		if len(helpers) != 1 {
			continue
		}
		wire, known := module.MethodNames[helpers[0]+"_Args"]
		if !known {
			continue
		}
		symbol := GeneratedSymbol{
			Protocol: "thrift", ImportPath: importPath, Package: file.Name.Name,
			ClientType: "Interface", Method: fn.Name.Name,
			Operation:     "/" + module.Name + "." + service + "/" + wire,
			GeneratedPath: generatedPath,
		}
		if constructor != "" {
			symbol.Constructors = []string{constructor}
		}
		result = append(result, symbol)
	}
	sort.Slice(result, func(i, j int) bool { return result[i].Method < result[j].Method })
	return result, nil
}

func yarpcInterfaceMethods(file *ast.File) map[string]struct{} {
	result := make(map[string]struct{})
	for _, declaration := range file.Decls {
		general, ok := declaration.(*ast.GenDecl)
		if !ok || general.Tok != token.TYPE {
			continue
		}
		for _, spec := range general.Specs {
			typeSpec, ok := spec.(*ast.TypeSpec)
			if !ok || typeSpec.Name.Name != "Interface" {
				continue
			}
			value, ok := typeSpec.Type.(*ast.InterfaceType)
			if !ok {
				continue
			}
			for _, field := range value.Methods.List {
				if _, isFunc := field.Type.(*ast.FuncType); !isFunc {
					continue
				}
				for _, name := range field.Names {
					result[name.Name] = struct{}{}
				}
			}
		}
	}
	return result
}

// yarpcService returns the one Service literal every thrift.Config in New
// names, and New itself when it returns Interface.
func yarpcService(file *ast.File) (service, constructor string) {
	for _, declaration := range file.Decls {
		fn, ok := declaration.(*ast.FuncDecl)
		if !ok || fn.Recv != nil || fn.Name.Name != "New" || fn.Body == nil ||
			fn.Type.Results == nil || len(fn.Type.Results.List) != 1 ||
			localTypeName(fn.Type.Results.List[0].Type) != "Interface" {
			continue
		}
		services := make(map[string]struct{})
		ast.Inspect(fn.Body, func(node ast.Node) bool {
			literal, ok := node.(*ast.CompositeLit)
			if !ok {
				return true
			}
			selector, ok := literal.Type.(*ast.SelectorExpr)
			if !ok || selector.Sel.Name != "Config" {
				return true
			}
			for _, element := range literal.Elts {
				pair, ok := element.(*ast.KeyValueExpr)
				if !ok {
					continue
				}
				if key, ok := pair.Key.(*ast.Ident); ok && key.Name == "Service" {
					if value, isString := stringLiteral(pair.Value); isString && value != "" {
						services[value] = struct{}{}
					}
				}
			}
			return true
		})
		if len(services) != 1 {
			return "", ""
		}
		for value := range services {
			service = value
		}
		return service, "New"
	}
	return "", ""
}

// yarpcHelperArgs returns the distinct T for every `<alias>.T_Helper.Args(...)`
// call in fn.
func yarpcHelperArgs(fn *ast.FuncDecl, alias string) []string {
	seen := make(map[string]struct{})
	ast.Inspect(fn.Body, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		args, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || args.Sel.Name != "Args" {
			return true
		}
		helper, ok := args.X.(*ast.SelectorExpr)
		if !ok || !strings.HasSuffix(helper.Sel.Name, "_Helper") {
			return true
		}
		if pkg, ok := helper.X.(*ast.Ident); ok && pkg.Name == alias {
			seen[strings.TrimSuffix(helper.Sel.Name, "_Helper")] = struct{}{}
		}
		return true
	})
	result := make([]string, 0, len(seen))
	for value := range seen {
		result = append(result, value)
	}
	sort.Strings(result)
	return result
}
