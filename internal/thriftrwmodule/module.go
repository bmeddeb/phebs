// Package thriftrwmodule reads the IDL a thriftrw-generated Go file embeds in
// its ThriftModule descriptor (PHEBS-47). It returns the decoded IDL together
// with the exact byte offset, in the Go file, of every decoded byte, so facts
// derived from the IDL can cite the Go file's own bytes.
package thriftrwmodule

import (
	"crypto/sha1" //nolint:gosec // thriftrw defines SHA1 as descriptor identity; this verifies it
	"encoding/hex"
	"errors"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"regexp"
	"strconv"
	"strings"
	"unicode/utf8"
)

var moduleHeader = regexp.MustCompile(`^// Code generated by thriftrw v[0-9]+\.[0-9]+\.[0-9]+[^\n]*\. DO NOT EDIT\.`)

// IsModuleSource reports whether content starts with a thriftrw generated-code
// header line.
func IsModuleSource(content string) bool {
	head := content
	if len(head) > 256 {
		head = head[:256]
	}
	return moduleHeader.MatchString(head)
}

// Embedded is one thriftrw module's descriptor and its decoded IDL.
type Embedded struct {
	Name, Package, FilePath, SHA1 string
	// Raw is the decoded IDL; Offsets[i] is the Go-file byte offset where the
	// encoding of Raw[i] starts, and Offsets[len(Raw)] is the closing quote.
	Raw     string
	Offsets []int
}

// DigestValid reports whether sha1(Raw) equals the descriptor's SHA1.
func (module Embedded) DigestValid() bool {
	sum := sha1.Sum([]byte(module.Raw)) //nolint:gosec // descriptor integrity
	return hex.EncodeToString(sum[:]) == module.SHA1
}

// ParseEmbedded returns the ThriftModule descriptor of a thriftrw module file.
// ok is false when content is not a thriftrw module source or declares no
// ThriftModule; err reports a descriptor whose shape cannot be read exactly.
func ParseEmbedded(filePath, content string) (module Embedded, ok bool, err error) {
	if !utf8.ValidString(content) || !IsModuleSource(content) {
		return Embedded{}, false, nil
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, filePath, content, parser.SkipObjectResolution)
	if err != nil {
		return Embedded{}, false, fmt.Errorf("parse Go: %w", err)
	}
	literal := moduleLiteral(file)
	if literal == nil {
		return Embedded{}, false, nil
	}
	var raw *ast.BasicLit
	for _, element := range literal.Elts {
		pair, isPair := element.(*ast.KeyValueExpr)
		if !isPair {
			continue
		}
		key, isIdent := pair.Key.(*ast.Ident)
		if !isIdent {
			continue
		}
		var target *string
		switch key.Name {
		case "Name":
			target = &module.Name
		case "Package":
			target = &module.Package
		case "FilePath":
			target = &module.FilePath
		case "SHA1":
			target = &module.SHA1
		case "Raw":
			value, resolveErr := resolveLiteral(file, pair.Value, map[string]bool{})
			if resolveErr != nil {
				return Embedded{}, false, fmt.Errorf("ThriftModule Raw: %w", resolveErr)
			}
			raw = value
			continue
		default:
			continue
		}
		value, resolveErr := resolveLiteral(file, pair.Value, map[string]bool{})
		if resolveErr != nil {
			return Embedded{}, false, fmt.Errorf("ThriftModule %s: %w", key.Name, resolveErr)
		}
		if *target, err = strconv.Unquote(value.Value); err != nil {
			return Embedded{}, false, fmt.Errorf("ThriftModule %s: %w", key.Name, err)
		}
	}
	if module.Name == "" || module.Package == "" || module.FilePath == "" ||
		!strings.HasSuffix(module.FilePath, ".thrift") || len(module.SHA1) != 40 || raw == nil {
		return Embedded{}, false, errors.New("ThriftModule descriptor is incomplete")
	}
	base := fset.Position(raw.Pos()).Offset
	module.Raw, module.Offsets, err = DecodeLiteral(raw.Value, base)
	if err != nil {
		return Embedded{}, false, fmt.Errorf("ThriftModule Raw: %w", err)
	}
	return module, true, nil
}

func moduleLiteral(file *ast.File) *ast.CompositeLit {
	for _, declaration := range file.Decls {
		general, isGeneral := declaration.(*ast.GenDecl)
		if !isGeneral || general.Tok != token.VAR {
			continue
		}
		for _, spec := range general.Specs {
			value, isValue := spec.(*ast.ValueSpec)
			if !isValue || len(value.Names) != 1 || value.Names[0].Name != "ThriftModule" ||
				len(value.Values) != 1 {
				continue
			}
			unary, isUnary := value.Values[0].(*ast.UnaryExpr)
			if !isUnary || unary.Op != token.AND {
				continue
			}
			literal, isLiteral := unary.X.(*ast.CompositeLit)
			if !isLiteral {
				continue
			}
			if selector, isSelector := literal.Type.(*ast.SelectorExpr); isSelector &&
				selector.Sel.Name == "ThriftModule" {
				return literal
			}
		}
	}
	return nil
}

// resolveLiteral follows a same-file const or var identifier to the single
// string literal it names; concatenations and other expressions are refused,
// because their bytes cannot be cited as one span.
func resolveLiteral(file *ast.File, expression ast.Expr, resolving map[string]bool) (*ast.BasicLit, error) {
	switch typed := expression.(type) {
	case *ast.BasicLit:
		if typed.Kind != token.STRING {
			return nil, errors.New("not a string literal")
		}
		return typed, nil
	case *ast.Ident:
		if resolving[typed.Name] {
			return nil, fmt.Errorf("cyclic declaration %s", typed.Name)
		}
		resolving[typed.Name] = true
		for _, declaration := range file.Decls {
			general, isGeneral := declaration.(*ast.GenDecl)
			if !isGeneral || (general.Tok != token.CONST && general.Tok != token.VAR) {
				continue
			}
			for _, spec := range general.Specs {
				value, isValue := spec.(*ast.ValueSpec)
				if !isValue {
					continue
				}
				for index, name := range value.Names {
					if name.Name == typed.Name && index < len(value.Values) {
						return resolveLiteral(file, value.Values[index], resolving)
					}
				}
			}
		}
		return nil, fmt.Errorf("identifier %s is not a same-file string declaration", typed.Name)
	default:
		return nil, errors.New("not a single string literal")
	}
}

// DecodeLiteral decodes one Go string literal (interpreted or raw) located at
// file offset base. offsets[i] is the file offset where decoded byte i's
// encoding starts; offsets[len(decoded)] is the offset of the closing quote.
func DecodeLiteral(literal string, base int) (decoded string, offsets []int, err error) {
	if len(literal) < 2 {
		return "", nil, errors.New("string literal is too short")
	}
	quote := literal[0]
	if literal[len(literal)-1] != quote || (quote != '"' && quote != '`') {
		return "", nil, errors.New("string literal is not quoted")
	}
	body := literal[1 : len(literal)-1]
	var out strings.Builder
	out.Grow(len(body))
	offsets = make([]int, 0, len(body)+1)
	if quote == '`' {
		if strings.ContainsRune(body, '\r') {
			// Go drops carriage returns from raw strings, so bytes and offsets
			// would no longer correspond one to one.
			return "", nil, errors.New("raw string literal contains a carriage return")
		}
		for index := range len(body) {
			offsets = append(offsets, base+1+index)
		}
		offsets = append(offsets, base+len(literal)-1)
		return body, offsets, nil
	}
	for index := 0; index < len(body); {
		start := base + 1 + index
		if body[index] != '\\' {
			out.WriteByte(body[index])
			offsets = append(offsets, start)
			index++
			continue
		}
		value, multibyte, tail, unquoteErr := strconv.UnquoteChar(body[index:], '"')
		if unquoteErr != nil {
			return "", nil, fmt.Errorf("escape at offset %d: %w", start, unquoteErr)
		}
		var encoded []byte
		if value < utf8.RuneSelf || !multibyte && value < 256 && isByteEscape(body[index:]) {
			encoded = []byte{byte(value)}
		} else {
			encoded = utf8.AppendRune(nil, value)
		}
		for _, current := range encoded {
			out.WriteByte(current)
			offsets = append(offsets, start)
		}
		index = len(body) - len(tail)
	}
	offsets = append(offsets, base+len(literal)-1)
	return out.String(), offsets, nil
}

// isByteEscape reports whether an escape denotes one byte (\x.. or octal)
// rather than a code point (\u, \U).
func isByteEscape(escape string) bool {
	return len(escape) > 1 && (escape[1] == 'x' || escape[1] >= '0' && escape[1] <= '7')
}
