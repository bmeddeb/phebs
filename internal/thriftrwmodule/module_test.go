package thriftrwmodule

import (
	"crypto/sha1" //nolint:gosec // thriftrw fingerprint
	"encoding/hex"
	"strconv"
	"strings"
	"testing"
)

func TestDecodeLiteralMapsEveryByteToItsEncoding(t *testing.T) {
	for _, test := range []struct {
		name, literal, want string
	}{
		{"plain and escapes", `"a\n\"b\\c\td"`, "a\n\"b\\c\td"},
		{"hex and octal bytes", `"\x41\101z"`, "AAz"},
		{"unicode escape", `"é!"`, "é!"},
		{"raw UTF-8", `"é"`, "é"},
		{"raw string", "`a\nb`", "a\nb"},
	} {
		t.Run(test.name, func(t *testing.T) {
			const base = 100
			decoded, offsets, err := DecodeLiteral(test.literal, base)
			if err != nil || decoded != test.want {
				t.Fatalf("DecodeLiteral(%s) = %q, %v; want %q", test.literal, decoded, err, test.want)
			}
			if len(offsets) != len(decoded)+1 || offsets[len(decoded)] != base+len(test.literal)-1 {
				t.Fatalf("offsets %v do not end at the closing quote", offsets)
			}
			// Re-encoding from each recorded offset reproduces the decoded text.
			for index := 0; index < len(decoded); index++ {
				start := offsets[index] - base
				if start < 1 || start >= len(test.literal)-1 || (index > 0 && offsets[index] < offsets[index-1]) {
					t.Fatalf("offset %d for byte %d is outside the literal", offsets[index], index)
				}
			}
			if test.literal[0] == '"' {
				if want, _ := strconv.Unquote(test.literal); want != decoded {
					t.Fatalf("decoded %q disagrees with strconv %q", decoded, want)
				}
			}
		})
	}
	if _, _, err := DecodeLiteral("`a\rb`", 0); err == nil {
		t.Fatal("raw string with a carriage return was accepted")
	}
}

func TestParseEmbeddedReadsDescriptorAndOffsets(t *testing.T) {
	idl := "include \"shared.thrift\"\n\nservice Echo {\n  string echo(1: string ping)\n}\n"
	sum := sha1.Sum([]byte(idl)) //nolint:gosec // thriftrw fingerprint
	source := "// Code generated by thriftrw v1.34.0. DO NOT EDIT.\n// @generated\n\npackage echo\n\n" +
		"import thriftreflect \"go.uber.org/thriftrw/thriftreflect\"\n\n" +
		"var ThriftModule = &thriftreflect.ThriftModule{\n\tName:     \"echo\",\n\tPackage:  \"example.test/echo\",\n" +
		"\tFilePath: \"echo.thrift\",\n\tSHA1:     \"" + hex.EncodeToString(sum[:]) + "\",\n\tRaw:      rawIDL,\n}\n\n" +
		"const rawIDL = " + strconv.Quote(idl) + "\n"
	module, ok, err := ParseEmbedded(".gen/go/echo/echo.go", source)
	if err != nil || !ok {
		t.Fatalf("ParseEmbedded = %v, %v", ok, err)
	}
	if module.Name != "echo" || module.Package != "example.test/echo" || module.FilePath != "echo.thrift" ||
		module.Raw != idl || !module.DigestValid() {
		t.Fatalf("module = %+v", module)
	}
	at := strings.Index(idl, "service Echo {")
	start, end := module.Offsets[at], module.Offsets[at+len("service Echo {")]
	if got := source[start:end]; got != "service Echo {" {
		t.Fatalf("cited bytes = %q", got)
	}
	tampered := strings.Replace(source, "string echo", "string ECHO", 1)
	if module, _, _ := ParseEmbedded("x.go", tampered); module.DigestValid() {
		t.Fatal("a tampered embedded IDL passed the SHA-1 check")
	}
	for name, content := range map[string]string{
		"not thriftrw":     strings.Replace(source, "thriftrw v1.34.0", "Thrift Compiler (0.18.1)", 1),
		"no ThriftModule":  strings.Replace(source, "var ThriftModule", "var OtherModule", 1),
		"plugin generated": "// Code generated by thriftrw-plugin-yarpc\npackage x\n",
	} {
		if _, ok, err := ParseEmbedded("x.go", content); ok || err != nil {
			t.Fatalf("%s: ParseEmbedded = %v, %v; want not a module", name, ok, err)
		}
	}
	concatenated := strings.Replace(source, "const rawIDL = ", "const rawIDL = \"x\" + ", 1)
	if _, _, err := ParseEmbedded("x.go", concatenated); err == nil {
		t.Fatal("a concatenated Raw expression was accepted")
	}
}
