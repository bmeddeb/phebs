// Modelled on grpc-go examples/helloworld: a committed .proto, the
// protoc-gen-go descriptor file and the protoc-gen-go-grpc client beside it,
// with no generated-from snapshot.
const (
	helloSource          = "helloworld/helloworld.proto"
	helloProtoPath       = "proto/" + helloSource
	helloDescriptorPath  = "gen/helloworld/helloworld.pb.go"
	helloClientPath      = "gen/helloworld/helloworld_grpc.pb.go"
	helloCallerPath      = "cmd/greeter/main.go"
	helloLineage         = "lineage-hello"
	helloImportPath      = "example.test/gen/helloworld"
	helloProto           = "syntax = \"proto3\";\npackage helloworld;\noption go_package = \"example.test/gen/helloworld\";\n\nmessage HelloRequest { string name = 1; }\nmessage HelloReply { string message = 1; }\n\nservice Greeter {\n  rpc SayHello (HelloRequest) returns (HelloReply);\n  rpc SayHelloAgain (stream HelloRequest) returns (HelloReply);\n}\n"
	helloClientSource    = "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\n// versions:\n// - protoc-gen-go-grpc v1.5.1\n// source: " + helloSource + "\n\npackage helloworld\n\nimport (\n\tcontext \"context\"\n\tgrpc \"google.golang.org/grpc\"\n)\n\nconst (\n\tGreeter_SayHello_FullMethodName      = \"/helloworld.Greeter/SayHello\"\n\tGreeter_SayHelloAgain_FullMethodName = \"/helloworld.Greeter/SayHelloAgain\"\n)\n\ntype GreeterClient interface {\n\tSayHello(ctx context.Context, in *HelloRequest, opts ...grpc.CallOption) (*HelloReply, error)\n\tSayHelloAgain(ctx context.Context, opts ...grpc.CallOption) (any, error)\n}\n\ntype greeterClient struct{ cc grpc.ClientConnInterface }\n\nfunc NewGreeterClient(cc grpc.ClientConnInterface) GreeterClient { return &greeterClient{cc} }\n\nvar Greeter_ServiceDesc = grpc.ServiceDesc{ServiceName: \"helloworld.Greeter\"}\n"
	helloCallerSource    = "package main\n\nimport (\n\t\"context\"\n\n\t\"example.test/gen/helloworld\"\n)\n\nfunc run(ctx context.Context, conn any) {\n\tc := helloworld.NewGreeterClient(conn)\n\t_, _ = c.SayHello(ctx, nil)\n\t_, _ = c.SayHelloAgain(ctx)\n}\n"
	helloDescriptorForms = "bytes"
)

// compiledDescriptor links one .proto (with the standard imports) the way
// protoc would before protoc-gen-go embeds it: no source info.
func compiledDescriptor(t *testing.T, name, content string) *descriptorpb.FileDescriptorProto {
	t.Helper()
	compiler := protocompile.Compiler{
		Resolver: protocompile.WithStandardImports(&protocompile.SourceResolver{
			Accessor: protocompile.SourceAccessorFromMap(map[string]string{name: content}),
		}),
	}
	files, err := compiler.Compile(context.Background(), name)
	if err != nil {
		t.Fatal(err)
	}
	return protodesc.ToFileDescriptorProto(files[0])
}

func goByteLiteral(raw []byte) string {
	var out strings.Builder
	out.WriteString("[]byte{")
	for index, value := range raw {
		if index > 0 {
			out.WriteString(", ")
		}
		fmt.Fprintf(&out, "0x%02x", value)
	}
	out.WriteString("}")
	return out.String()
}

// descriptorGoSource renders a protoc-gen-go file embedding descriptor in one
// of the emitted forms: "bytes" ([]byte{...}), "string" (a concatenated string
// constant, protoc-gen-go >= 1.36) or "legacy" (gzipped fileDescriptor_*).
func descriptorGoSource(t *testing.T, descriptor *descriptorpb.FileDescriptorProto, form string) string {
	t.Helper()
	raw, err := proto.Marshal(descriptor)
	if err != nil {
		t.Fatal(err)
	}
	header := "// Code generated by protoc-gen-go. DO NOT EDIT.\n// source: " + descriptor.GetName() +
		"\n\npackage helloworld\n\n"
	switch form {
	case "bytes":
		return header + "var file_helloworld_helloworld_proto_rawDesc = " + goByteLiteral(raw) + "\n"
	case "string":
		half := len(raw) / 2
		return header + "const file_helloworld_helloworld_proto_rawDesc = \"\" +\n\t" +
			strconv.Quote(string(raw[:half])) + " +\n\t" + strconv.Quote(string(raw[half:])) + "\n"
	case "legacy":
		var compressed bytes.Buffer
		writer := gzip.NewWriter(&compressed)
		_, _ = writer.Write(raw)
		_ = writer.Close()
		return header + "var fileDescriptor_0123abcd = " + goByteLiteral(compressed.Bytes()) + "\n"
	}
	t.Fatalf("unknown descriptor form %q", form)
	return ""
}

type helloFixture struct {
	form            string            // descriptor literal form; default "bytes"
	generatedProto  string            // the .proto the generated code was built from; default helloProto
	declaredProtos  map[string]string // declared .proto files; default {helloProtoPath: helloProto}
	noDescriptor    bool              // no protoc-gen-go file beside the client
	extraDescriptor bool              // a second descriptor of the same source in the directory
	snapshot        bool              // an explicit generated-from mapping names the client
}

func buildHelloCatalog(t *testing.T, fixture helloFixture) *CallerResolverView {
	t.Helper()
	if fixture.form == "" {
		fixture.form = helloDescriptorForms
	}
	if fixture.generatedProto == "" {
		fixture.generatedProto = helloProto
	}
	if fixture.declaredProtos == nil {
		fixture.declaredProtos = map[string]string{helloProtoPath: helloProto}
	}
	blobs := newMaterializeBlobFixture()
	files := []extract.CandidateManifestFile{
		blobs.add("go.mod", "module \"example.test\"\n"),
		blobs.add(helloCallerPath, helloCallerSource),
		blobs.add(helloClientPath, helloClientSource),
	}
	if !fixture.noDescriptor {
		descriptor := compiledDescriptor(t, helloSource, fixture.generatedProto)
		files = append(files, blobs.add(helloDescriptorPath, descriptorGoSource(t, descriptor, fixture.form)))
		if fixture.extraDescriptor {
			files = append(files, blobs.add("gen/helloworld/copy.pb.go", descriptorGoSource(t, descriptor, "legacy")))
		}
	}
	declaredPaths := make([]string, 0, len(fixture.declaredProtos))
	for declaredPath := range fixture.declaredProtos {
		declaredPaths = append(declaredPaths, declaredPath)
	}
	slices.Sort(declaredPaths)
	grpc := materializeTestDeclaration(ProtocolGRPC)
	var rows []store.Assertion
	for index, declaredPath := range declaredPaths {
		files = append(files, blobs.add(declaredPath, fixture.declaredProtos[declaredPath]))
		for methodIndex, method := range []string{"SayHello", "SayHelloAgain"} {
			row := materializeTestAssertion(grpc.RunID, declaredPath, helloLineage, 2*index+methodIndex+1)
			if index > 0 {
				row.Lineage = "lineage-hello-" + strconv.Itoa(index)
			}
			row.Object = "helloworld.Greeter/" + method
			rows = append(rows, row)
		}
	}
	if fixture.snapshot {
		files = append(files, blobs.add(resolverinput.GeneratedFromSnapshotPath,
			`{"version":"t20-generated-from-v1","mappings":[{"protocol":"grpc","generated_path":"`+
				helloClientPath+`","declaration_path":"`+helloProtoPath+`"}]}`))
	}
	root := t.TempDir()
	request := newMaterializeBuildRequest(
		t, root, newMaterializeTestRegistry(t, ProtocolGRPC),
		&materializeTestManifest{identity: testManifestDigest, files: files}, blobs,
		[]DeclarationInput{grpc},
		newMaterializePublishedAssertions(map[string][]store.Assertion{grpc.RunID: rows}),
	)
	prepared, err := Build(context.Background(), request)
	if err != nil {
		t.Fatal(err)
	}
	state, err := prepared.Publish(context.Background(),
		func(context.Context, resolvercatalog.State) error { return nil })
	if err != nil {
		t.Fatal(err)
	}
	_, views, err := OpenCallerResolvers(context.Background(), root, state, []Protocol{ProtocolGRPC})
	if err != nil {
		t.Fatal(err)
	}
	return views[ProtocolGRPC]
}

func scanHelloCaller(t *testing.T, view *CallerResolverView) (calls, unresolved []string) {
	t.Helper()
	sum := sha256.Sum256([]byte(helloCallerSource))
	if _, err := gocaller.ScanDirectSyntaxFile(context.Background(), gocaller.DirectScanRequest{
		Protocol: "grpc", Path: helloCallerPath,
		Blob:     sdk.Blob{Content: helloCallerSource, Digest: "sha256:" + hex.EncodeToString(sum[:])},
		Resolver: view.Resolver(), ResolverCatalogDigest: "sha256:" + strings.Repeat("a", 64),
	}, func(fact sdk.Fact) error {
		switch fact.Assertion.Predicate {
		case "CALLS_OPERATION":
			if fact.Assertion.Lineage != helloLineage {
				t.Errorf("call %s lineage = %q", fact.Assertion.Object, fact.Assertion.Lineage)
			}
			calls = append(calls, fact.Assertion.Object)
		case "UNRESOLVED_CALLER":
			unresolved = append(unresolved, fact.Assertion.Object)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	slices.Sort(calls)
	return calls, unresolved
}

// TestProtoDescriptorProvenanceResolvesGRPCCallers is the PHEBS-49 end-to-end
// check: with no generated-from snapshot, the protoc-gen-go descriptor beside
// a protoc-gen-go-grpc client equals exactly one committed .proto, so the
// client's callers resolve to that declaration, for every literal form
// protoc-gen-go emits.
func TestProtoDescriptorProvenanceResolvesGRPCCallers(t *testing.T) {
	policy := FrozenMaterializationPolicy()
	if PackVersion != "1.7.0" || ProtoDescriptorProvenance != "protoc-gen-go-embedded-descriptor-equal-v1" ||
		policy.ProtoDescriptorProvenance != ProtoDescriptorProvenance ||
		policy.MaxProtoDescriptorCandidates != MaxProtoDescriptorCandidates ||
		policy.MaxProtoDescriptorBytes != MaxProtoDescriptorBytes {
		t.Fatalf("descriptor provenance identity = %q / %q", ProtoDescriptorProvenance, PackVersion)
	}
	for _, form := range []string{"bytes", "string", "legacy"} {
		t.Run(form, func(t *testing.T) {
			view := buildHelloCatalog(t, helloFixture{form: form})
			descriptors := view.Descriptors()
			if len(descriptors) != 2 {
				t.Fatalf("descriptors = %+v, want two", descriptors)
			}
			for _, got := range descriptors {
				if got.State != StateResolved || got.Reason != "" ||
					got.DeclarationPath != helloProtoPath || got.DeclarationLineage != helloLineage ||
					got.ImportPath != helloImportPath || got.ClientType != "GreeterClient" ||
					got.GeneratedPath != helloClientPath ||
					!slices.Equal(got.Constructors, []string{"NewGreeterClient"}) {
					t.Fatalf("%s descriptor = %+v, want resolved to %s", got.Method, got, helloProtoPath)
				}
			}
			calls, unresolved := scanHelloCaller(t, view)
			want := []string{"/helloworld.Greeter/SayHello", "/helloworld.Greeter/SayHelloAgain"}
			if !slices.Equal(calls, want) || len(unresolved) != 0 {
				t.Fatalf("calls = %v (unresolved %v), want %v", calls, unresolved, want)
			}
		})
	}
}

// TestProtoDescriptorProvenanceAbstains covers every relation the rule
// refuses: the client's calls stay explicit abstentions with no declaration.
func TestProtoDescriptorProvenanceAbstains(t *testing.T) {
	stale := strings.Replace(helloProto, "string message = 1;", "string message = 1; int32 code = 2;", 1)
	otherGoPackage := strings.Replace(helloProto, "example.test/gen/helloworld", "example.test/elsewhere", 1)
	for _, test := range []struct {
		name    string
		fixture helloFixture
		state   string
		reason  string
	}{
		{name: "generated from an older proto", fixture: helloFixture{generatedProto: stale},
			state: StateUnavailable, reason: "proto_descriptor_mismatch"},
		{name: "go_package differs", fixture: helloFixture{generatedProto: otherGoPackage},
			state: StateUnavailable, reason: "proto_descriptor_mismatch"},
		{name: "two committed copies match", fixture: helloFixture{declaredProtos: map[string]string{
			helloProtoPath: helloProto, "vendor/protos/" + helloSource: helloProto,
		}}, state: StateAmbiguous, reason: "proto_declaration_ambiguous"},
		{name: "proto not committed", fixture: helloFixture{declaredProtos: map[string]string{
			"proto/other/greeter.proto": helloProto,
		}}, state: StateUnavailable, reason: "proto_declaration_not_declared"},
		{name: "no descriptor beside the client", fixture: helloFixture{noDescriptor: true},
			state: StateUnavailable, reason: "proto_descriptor_missing"},
		{name: "two descriptors of the same source", fixture: helloFixture{extraDescriptor: true},
			state: StateAmbiguous, reason: "proto_descriptor_ambiguous"},
	} {
		t.Run(test.name, func(t *testing.T) {
			view := buildHelloCatalog(t, test.fixture)
			descriptors := view.Descriptors()
			if len(descriptors) != 2 {
				t.Fatalf("descriptors = %+v; an abstaining client must still be described", descriptors)
			}
			for _, got := range descriptors {
				if got.State != test.state || got.Reason != test.reason ||
					got.DeclarationPath != "" || got.DeclarationLineage != "" {
					t.Fatalf("%s descriptor = %+v, want %s/%s", got.Method, got, test.state, test.reason)
				}
			}
			calls, unresolved := scanHelloCaller(t, view)
			if len(calls) != 0 || len(unresolved) != 2 {
				t.Fatalf("calls %v unresolved %v; want two abstentions", calls, unresolved)
			}
		})
	}
}

// TestProtoDescriptorProvenanceDefersToExplicitMapping keeps an explicit
// generated-from mapping authoritative: the derived pass skips the file.
func TestProtoDescriptorProvenanceDefersToExplicitMapping(t *testing.T) {
	view := buildHelloCatalog(t, helloFixture{snapshot: true, generatedProto: strings.Replace(
		helloProto, "string name = 1;", "string name = 1; string locale = 2;", 1)})
	descriptors := view.Descriptors()
	if len(descriptors) == 0 {
		t.Fatal("explicitly mapped client was not described")
	}
	for _, got := range descriptors {
		if got.Reason == "proto_descriptor_mismatch" {
			t.Fatalf("derived provenance overrode an explicit mapping: %+v", got)
		}
	}
}

// TestDescriptorsEquivalentShapes checks the comparison against linked
// descriptors for the shapes the parser represents differently: map entries,
// oneofs, proto3 optional, nested and imported types, enums and proto2.
func TestDescriptorsEquivalentShapes(t *testing.T) {
	const rich = `syntax = "proto3";
package acme.v1;
import "google/protobuf/empty.proto";
import "google/protobuf/timestamp.proto";
option go_package = "example.test/acme/v1;acmev1";

enum Color { COLOR_UNSPECIFIED = 0; RED = 1; }
message Outer {
  message Inner { Color color = 1; }
  enum Kind { KIND_UNSPECIFIED = 0; BIG = 1; }
  map<string, Inner> inners = 1;
  oneof choice { string text = 2; Inner inner = 3; }
  optional int64 count = 4;
  repeated Kind kinds = 5;
  google.protobuf.Timestamp at = 6;
  acme.v1.Color qualified = 7;
  .acme.v1.Outer.Inner absolute = 8;
}
service Things {
  rpc Get (Outer.Inner) returns (google.protobuf.Empty);
  rpc Watch (google.protobuf.Empty) returns (stream Outer);
}
`
	const legacy = `syntax = "proto2";
package old;
message Req { required string id = 1; optional group Extra = 2 { optional int32 n = 3; } }
message Res { repeated Req reqs = 1; }
service Old { rpc Do (Req) returns (Res); }
`
	for name, source := range map[string]string{"rich.proto": rich, "legacy.proto": legacy} {
		generated := compiledDescriptor(t, name, source)
		declared, err := parseDeclaredProto(context.Background(), "idl/"+name, source)
		if err != nil {
			t.Fatal(err)
		}
		if !descriptorsEquivalent(generated, declared) {
			t.Fatalf("%s: linked and unlinked descriptors of the same source are not equivalent", name)
		}
	}
	for name, change := range map[string][2]string{
		"field number":    {"map<string, Inner> inners = 1;", "map<string, Inner> inners = 9;"},
		"map value type":  {"map<string, Inner> inners = 1;", "map<string, Color> inners = 1;"},
		"streaming":       {"returns (stream Outer)", "returns (Outer)"},
		"enum value":      {"BIG = 1;", "BIG = 2;"},
		"import":          {"import \"google/protobuf/timestamp.proto\";\n", "import \"google/protobuf/timestamp.proto\";\nimport \"google/protobuf/duration.proto\";\n"},
		"proto3 optional": {"optional int64 count = 4;", "int64 count = 4;"},
	} {
		changed := strings.Replace(rich, change[0], change[1], 1)
		if changed == rich {
			t.Fatalf("%s: change did not apply", name)
		}
		generated := compiledDescriptor(t, "rich.proto", changed)
		declared, err := parseDeclaredProto(context.Background(), "idl/rich.proto", rich)
		if err != nil {
			t.Fatal(err)
		}
		if descriptorsEquivalent(generated, declared) {
			t.Fatalf("%s: different descriptors compared equivalent", name)
		}
	}
}

// TestLocalProtoNamesResolveByScope pins the scoping rule: a written name
// resolves from the innermost scope outward, a name the file declares
// shadows outer and imported names, and an imported name is accepted only
// when the file declares no type of that name.
func TestLocalProtoNamesResolveByScope(t *testing.T) {
	declared, err := parseDeclaredProto(context.Background(), "a.proto", `syntax = "proto3";
package a.b;
message Empty {}
message Outer { message Empty {} Empty inner = 1; }
`)
	if err != nil {
		t.Fatal(err)
	}
	local := newLocalProtoNames(declared)
	for _, test := range []struct {
		qualified, written, scope string
		want                      bool
	}{
		{".a.b.Outer.Empty", "Empty", ".a.b.Outer", true},
		{".a.b.Empty", "Empty", ".a.b.Outer", false},
		{".a.b.Empty", "Empty", ".a.b", true},
		{".google.protobuf.Empty", "Empty", ".a.b", false},
		{".google.protobuf.Empty", "google.protobuf.Empty", ".a.b", true},
		{".a.b.Empty", "b.Empty", ".a.b", true},
		{".a.b.Empty", ".a.b.Empty", ".a.b.Outer", true},
		{".x.Empty", ".a.b.Empty", ".a.b", false},
		{"", "Empty", ".a.b", false},
	} {
		if got := local.resolves(test.qualified, test.written, test.scope); got != test.want {
			t.Errorf("resolves(%q, %q, %q) = %v, want %v", test.qualified, test.written, test.scope, got, test.want)
		}
	}
}

// TestEmbeddedFileDescriptorsBounds rejects literals the rule cannot evaluate
// or that exceed the decoded bound, and ignores files with no descriptor.
func TestEmbeddedFileDescriptorsBounds(t *testing.T) {
	if _, found, err := embeddedFileDescriptors("x.pb.go", []byte("package x\n")); err != nil || len(found) != 0 {
		t.Fatalf("plain file = %v, %v", found, err)
	}
	for name, source := range map[string]string{
		"non-literal":      "package x\nvar file_x_proto_rawDesc = make([]byte, 3)\n",
		"not a descriptor": "package x\nvar file_x_proto_rawDesc = []byte{0xff, 0xff}\n",
		"bad gzip":         "package x\nvar fileDescriptor_00ff = []byte{0x01}\n",
		"oversized":        "package x\nconst file_x_proto_rawDesc = \"" + strings.Repeat("a", MaxProtoDescriptorBytes+1) + "\"\n",
	} {
		if _, _, err := embeddedFileDescriptors("x.pb.go", []byte(source)); err == nil {
			t.Errorf("%s: decoded without error", name)
		}
	}
}
