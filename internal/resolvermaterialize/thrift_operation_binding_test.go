// hiveServerGeneratedSource has the shape the Apache Thrift compiler emits for
// HiveServer.thrift without a `namespace go`: the Go package is the lowercased
// IDL name, so its operations do not spell the declared Thrift scope.
const hiveServerGeneratedSource = `// Code generated by Thrift Compiler (0.18.1). DO NOT EDIT.

package hiveserver

import "context"

type TClient interface {
	Call(ctx context.Context, method string, args, result any) error
}

type TCLIServiceClient struct{ c TClient }

func NewTCLIServiceClientFactory(transport, protocol any) *TCLIServiceClient {
	return &TCLIServiceClient{}
}

func (p *TCLIServiceClient) Client_() TClient { return p.c }

func (p *TCLIServiceClient) OpenSession(ctx context.Context, req any) (any, error) {
	err := p.Client_().Call(ctx, "OpenSession", req, nil)
	return nil, err
}

func (p *TCLIServiceClient) ExecuteStatement(ctx context.Context, req any) (any, error) {
	err := p.Client_().Call(ctx, "ExecuteStatement", req, nil)
	return nil, err
}

func (p *TCLIServiceClient) FetchResults(ctx context.Context, req any) (any, error) {
	err := p.Client_().Call(ctx, "FetchResults", req, nil)
	return nil, err
}
`

// hiveCallerSource mirrors beltran/gohive's hive.go: a local client from the
// generated factory, and calls through a struct field typed as that client.
const hiveCallerSource = `package gohive

import (
	"context"

	"example.invalid/root/gen/thrift/hiveserver"
)

type connection struct{ client *hiveserver.TCLIServiceClient }

type Cursor struct{ conn *connection }

func open() {
	client := hiveserver.NewTCLIServiceClientFactory(nil, nil)
	client.OpenSession(context.Background(), nil)
}

func (c *Cursor) exec() {
	c.conn.client.ExecuteStatement(context.Background(), nil)
	c.conn.client.FetchResults(context.Background(), nil)
}
`

// TestThriftGeneratedSymbolBindsToMappedDeclarationSpelling is the PHEBS-42
// regression found on dave against beltran/gohive: a Thrift generated symbol
// takes the operation its mapped declaration declares for the same service
// and method (ThriftOperationBinding), so callers resolve to the Contract Atlas
// operation even when the generated Go package is not the Thrift scope. A
// generated method the declaration does not declare is an explicit abstention.
func TestThriftGeneratedSymbolBindsToMappedDeclarationSpelling(t *testing.T) {
	if ThriftOperationBinding != "mapped-declaration-service-method-v1" ||
		FrozenMaterializationPolicy().ThriftOperationBinding != ThriftOperationBinding ||
		PackVersion != "1.6.0" {
		t.Fatalf("Thrift operation binding identity = %q / %q", ThriftOperationBinding, PackVersion)
	}
	const (
		generatedPath   = "gen/thrift/hiveserver/HiveServer.go"
		declarationPath = "idl/thrift/HiveServer.thrift"
		lineage         = "lineage-hiveserver"
	)
	blobs := newMaterializeBlobFixture()
	layout := `{"version":"t20-layout-snapshot-v1","roots":[` +
		`{"kind":"idl","path":"idl/thrift","protocol":"thrift"},` +
		`{"kind":"generated","path":"gen/thrift","protocol":"thrift"}]}`
	mapping := `{"version":"t20-generated-from-v1","mappings":[` +
		`{"protocol":"thrift","generated_path":"` + generatedPath + `",` +
		`"declaration_path":"` + declarationPath + `"}]}`
	files := []extract.CandidateManifestFile{
		blobs.add("go.mod", "module \"example.invalid/root\"\n"),
		blobs.add("src/hive.go", hiveCallerSource),
		blobs.add(generatedPath, hiveServerGeneratedSource),
		blobs.add(resolverinput.LayoutSnapshotPath, layout),
		blobs.add(resolverinput.GeneratedFromSnapshotPath, mapping),
		blobs.add(declarationPath, "service TCLIService {}\n"),
	}
	thrift := materializeTestDeclaration(ProtocolThrift)
	declared := func(index int, object string) store.Assertion {
		row := materializeTestAssertion(thrift.RunID, declarationPath, lineage, index)
		row.Object = object
		return row
	}
	assertions := newMaterializePublishedAssertions(map[string][]store.Assertion{
		thrift.RunID: {
			declared(1, "HiveServer.TCLIService/ExecuteStatement"),
			declared(2, "HiveServer.TCLIService/OpenSession"),
		},
	})
	root := t.TempDir()
	request := newMaterializeBuildRequest(
		t, root, newMaterializeTestRegistry(t, ProtocolThrift),
		&materializeTestManifest{identity: testManifestDigest, files: files}, blobs,
		[]DeclarationInput{thrift}, assertions,
	)
	prepared, err := Build(context.Background(), request)
	if err != nil {
		t.Fatal(err)
	}
	state, err := prepared.Publish(
		context.Background(),
		func(context.Context, resolvercatalog.State) error { return nil },
	)
	if err != nil {
		t.Fatal(err)
	}
	_, views, err := OpenCallerResolvers(
		context.Background(), root, state, []Protocol{ProtocolThrift},
	)
	if err != nil {
		t.Fatal(err)
	}
	view := views[ProtocolThrift]
	byMethod := make(map[string]gocaller.DirectDescriptor)
	for _, descriptor := range view.Descriptors() {
		byMethod[descriptor.Method] = descriptor
	}
	for method, operation := range map[string]string{
		"OpenSession":      "/HiveServer.TCLIService/OpenSession",
		"ExecuteStatement": "/HiveServer.TCLIService/ExecuteStatement",
	} {
		got := byMethod[method]
		if got.State != StateResolved || got.Operation != operation ||
			got.DeclarationLineage != lineage || got.Package != "hiveserver" {
			t.Fatalf("%s descriptor = %+v, want resolved %s", method, got, operation)
		}
	}
	if fetch := byMethod["FetchResults"]; fetch.State != StateUnavailable ||
		fetch.Reason != "operation_not_declared" || fetch.DeclarationLineage != "" {
		t.Fatalf("undeclared FetchResults descriptor = %+v", fetch)
	}

	sum := sha256.Sum256([]byte(hiveCallerSource))
	var calls, unresolved []string
	if _, err := gocaller.ScanDirectSyntaxFile(context.Background(), gocaller.DirectScanRequest{
		Protocol: "thrift", Path: "src/hive.go",
		Blob:     sdk.Blob{Content: hiveCallerSource, Digest: "sha256:" + hex.EncodeToString(sum[:])},
		Resolver: view.Resolver(), ResolverCatalogDigest: "sha256:" + strings.Repeat("a", 64),
	}, func(fact sdk.Fact) error {
		switch fact.Assertion.Predicate {
		case "CALLS_OPERATION":
			if fact.Assertion.Lineage != lineage {
				t.Errorf("call %s lineage = %q", fact.Assertion.Object, fact.Assertion.Lineage)
			}
			calls = append(calls, fact.Assertion.Object)
		case "UNRESOLVED_CALLER":
			unresolved = append(unresolved, fact.Assertion.Object)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	slices.Sort(calls)
	if want := []string{
		"/HiveServer.TCLIService/ExecuteStatement", "/HiveServer.TCLIService/OpenSession",
	}; !slices.Equal(calls, want) {
		t.Fatalf("resolved Thrift calls = %v, want %v", calls, want)
	}
	if len(unresolved) != 1 {
		t.Fatalf("undeclared FetchResults call = %v, want one explicit abstention", unresolved)
	}
}

func TestThriftServiceMethodKey(t *testing.T) {
	for operation, want := range map[string]string{
		"/HiveServer.TCLIService/OpenSession": "TCLIService/OpenSession",
		"HiveServer.TCLIService/OpenSession":  "TCLIService/OpenSession",
		"/hiveserver.TCLIService/OpenSession": "TCLIService/OpenSession",
		"/a.b.Service/m":                      "Service/m",
		"/Service/m":                          "",
		"/scope.Service/":                     "",
		"/scope./m":                           "",
		"/scope.Service/m/extra":              "",
	} {
		got, ok := thriftServiceMethod(operation)
		if ok != (want != "") || got != want {
			t.Fatalf("thriftServiceMethod(%q) = %q, %t; want %q", operation, got, ok, want)
		}
	}
	targets := &declarationTargets{operations: make(map[string]map[string][]string)}
	budget := &materializationBudget{}
	for _, operation := range []string{
		"HiveServer.TCLIService/OpenSession", "/HiveServer.TCLIService/OpenSession",
		"Other.TCLIService/Ambiguous", "Third.TCLIService/Ambiguous",
	} {
		if err := targets.addThriftOperation(budget, "lineage", operation); err != nil {
			t.Fatal(err)
		}
	}
	if operation, bound, _ := targets.bindThriftOperation(
		"lineage", "/hiveserver.TCLIService/OpenSession",
	); !bound || operation != "/HiveServer.TCLIService/OpenSession" {
		t.Fatalf("bind = %q %t", operation, bound)
	}
	for generated, reason := range map[string]string{
		"/x.TCLIService/Missing":   "operation_not_declared",
		"/x.TCLIService/Ambiguous": "operation_declared_ambiguously",
		"no-slash-or-dot":          "generated_operation_unkeyed",
	} {
		if _, bound, got := targets.bindThriftOperation("lineage", generated); bound || got != reason {
			t.Fatalf("bind %q = %t %q, want %q", generated, bound, got, reason)
		}
	}
	if _, bound, got := targets.bindThriftOperation("other-lineage", "/x.TCLIService/OpenSession"); bound ||
		got != "operation_not_declared" {
		t.Fatalf("cross-lineage bind = %t %q", bound, got)
	}
	if budget.declarationOperationBytes != len("/HiveServer.TCLIService/OpenSession")+
		len("/Other.TCLIService/Ambiguous")+len("/Third.TCLIService/Ambiguous") {
		t.Fatalf("operation budget = %d", budget.declarationOperationBytes)
	}
}
