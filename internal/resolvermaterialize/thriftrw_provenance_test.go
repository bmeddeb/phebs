// Modelled on yarpc-go internal/crossdock/thrift/echo: a committed echo.thrift,
// its thriftrw package (embedding ThriftModule provenance) and the
// thriftrw-plugin-yarpc client, with no generated-from snapshot.
const (
	yarpcIDLPath     = "thrift/echo.thrift"
	yarpcModulePath  = "thrift/echo/echo.go"
	yarpcClientPath  = "thrift/echo/echoclient/client.go"
	yarpcCallerPath  = "cmd/caller/main.go"
	yarpcLineage     = "lineage-echo"
	yarpcIDLContent  = "service Echo {\n  string echo(1: string ping)\n  void ping_twice()\n}\n"
	yarpcClientInput = `// Code generated by thriftrw-plugin-yarpc
// @generated

package echoclient

import (
	context "context"
	yarpc "go.uber.org/yarpc"
	transport "go.uber.org/yarpc/api/transport"
	thrift "go.uber.org/yarpc/encoding/thrift"
	echo "example.test/thrift/echo"
)

type Interface interface {
	Echo(ctx context.Context, Ping string, opts ...yarpc.CallOption) (string, error)
	PingTwice(ctx context.Context, opts ...yarpc.CallOption) error
}

func New(c transport.ClientConfig, opts ...thrift.ClientOption) Interface {
	return client{c: thrift.New(thrift.Config{Service: "Echo", ClientConfig: c}, opts...)}
}

type client struct{ c thrift.Client }

func (c client) Echo(ctx context.Context, _Ping string, opts ...yarpc.CallOption) (success string, err error) {
	args := echo.Echo_Echo_Helper.Args(_Ping)
	_, err = c.c.Call(ctx, args, opts...)
	return
}

func (c client) PingTwice(ctx context.Context, opts ...yarpc.CallOption) (err error) {
	args := echo.Echo_PingTwice_Helper.Args()
	_, err = c.c.Call(ctx, args, opts...)
	return
}
`
	yarpcCallerSource = `package main

import (
	"context"

	"example.test/thrift/echo/echoclient"
)

func run(ctx context.Context, cfg any) {
	c := echoclient.New(cfg)
	_, _ = c.Echo(ctx, "hello")
	var iface echoclient.Interface = c
	_ = iface.PingTwice(ctx)
}
`
)

func yarpcModuleSource(pkg, sum string) string {
	return `// Code generated by thriftrw v1.32.0. DO NOT EDIT.
// @generated

package echo

import thriftreflect "go.uber.org/thriftrw/thriftreflect"

type Echo_Echo_Args struct{}

func (v *Echo_Echo_Args) MethodName() string {
	return "echo"
}

type Echo_PingTwice_Args struct{}

func (v *Echo_PingTwice_Args) MethodName() string {
	return "ping_twice"
}

var ThriftModule = &thriftreflect.ThriftModule{
	Name:     "echo",
	Package:  "` + pkg + `",
	FilePath: "echo.thrift",
	SHA1:     "` + sum + `",
	Raw:      rawIDL,
}

const rawIDL = "service Echo {}"
`
}

type yarpcFixture struct {
	modulePackage string
	moduleSHA1    string
	extraIDLPath  string // a second declared .thrift with the same name and content
	snapshot      bool   // an explicit generated-from mapping names the client
}

func buildYARPCCatalog(t *testing.T, fixture yarpcFixture) *CallerResolverView {
	t.Helper()
	sum := sha1.Sum([]byte(yarpcIDLContent)) //nolint:gosec // thriftrw fingerprint
	if fixture.modulePackage == "" {
		fixture.modulePackage = "example.test/thrift/echo"
	}
	if fixture.moduleSHA1 == "" {
		fixture.moduleSHA1 = hex.EncodeToString(sum[:])
	}
	blobs := newMaterializeBlobFixture()
	files := []extract.CandidateManifestFile{
		blobs.add("go.mod", "module \"example.test\"\n"),
		blobs.add(yarpcCallerPath, yarpcCallerSource),
		blobs.add(yarpcIDLPath, yarpcIDLContent),
		blobs.add(yarpcModulePath, yarpcModuleSource(fixture.modulePackage, fixture.moduleSHA1)),
		blobs.add(yarpcClientPath, yarpcClientInput),
	}
	if fixture.extraIDLPath != "" {
		files = append(files, blobs.add(fixture.extraIDLPath, yarpcIDLContent))
	}
	if fixture.snapshot {
		files = append(files, blobs.add(resolverinput.GeneratedFromSnapshotPath,
			`{"version":"t20-generated-from-v1","mappings":[{"protocol":"thrift","generated_path":"`+
				yarpcClientPath+`","declaration_path":"`+yarpcIDLPath+`"}]}`))
	}
	thrift := materializeTestDeclaration(ProtocolThrift)
	var rows []store.Assertion
	for index, declared := range []struct{ path, object string }{
		{yarpcIDLPath, "echo.Echo/echo"}, {yarpcIDLPath, "echo.Echo/ping_twice"},
		{fixture.extraIDLPath, "echo.Echo/echo"},
	} {
		if declared.path == "" {
			continue
		}
		row := materializeTestAssertion(thrift.RunID, declared.path, yarpcLineage, index+1)
		if declared.path != yarpcIDLPath {
			row.Lineage = "lineage-other-echo"
		}
		row.Object = declared.object
		rows = append(rows, row)
	}
	root := t.TempDir()
	request := newMaterializeBuildRequest(
		t, root, newMaterializeTestRegistry(t, ProtocolThrift),
		&materializeTestManifest{identity: testManifestDigest, files: files}, blobs,
		[]DeclarationInput{thrift},
		newMaterializePublishedAssertions(map[string][]store.Assertion{thrift.RunID: rows}),
	)
	prepared, err := Build(context.Background(), request)
	if err != nil {
		t.Fatal(err)
	}
	state, err := prepared.Publish(context.Background(),
		func(context.Context, resolvercatalog.State) error { return nil })
	if err != nil {
		t.Fatal(err)
	}
	_, views, err := OpenCallerResolvers(context.Background(), root, state, []Protocol{ProtocolThrift})
	if err != nil {
		t.Fatal(err)
	}
	return views[ProtocolThrift]
}

func scanYARPCCaller(t *testing.T, view *CallerResolverView) (calls, unresolved []string) {
	t.Helper()
	sum := sha256.Sum256([]byte(yarpcCallerSource))
	if _, err := gocaller.ScanDirectSyntaxFile(context.Background(), gocaller.DirectScanRequest{
		Protocol: "thrift", Path: yarpcCallerPath,
		Blob:     sdk.Blob{Content: yarpcCallerSource, Digest: "sha256:" + hex.EncodeToString(sum[:])},
		Resolver: view.Resolver(), ResolverCatalogDigest: "sha256:" + strings.Repeat("a", 64),
	}, func(fact sdk.Fact) error {
		switch fact.Assertion.Predicate {
		case "CALLS_OPERATION":
			if fact.Assertion.Lineage != yarpcLineage {
				t.Errorf("call %s lineage = %q", fact.Assertion.Object, fact.Assertion.Lineage)
			}
			calls = append(calls, fact.Assertion.Object)
		case "UNRESOLVED_CALLER":
			unresolved = append(unresolved, fact.Assertion.Object)
		}
		return nil
	}); err != nil {
		t.Fatal(err)
	}
	slices.Sort(calls)
	return calls, unresolved
}

// TestThriftRWProvenanceResolvesYARPCCallers is the PHEBS-46 end-to-end check:
// with no generated-from snapshot, hash-verified thriftrw provenance relates a
// YARPC client to its committed .thrift file, the Thrift method keeps its
// wire spelling (Go PingTwice is ping_twice), and callers holding
// echoclient.New(...) or an echoclient.Interface value resolve.
func TestThriftRWProvenanceResolvesYARPCCallers(t *testing.T) {
	if PackVersion != "1.4.0" || ThriftRWProvenance != "thriftrw-yarpc-module-package-sha1-v1" ||
		FrozenMaterializationPolicy().ThriftRWProvenance != ThriftRWProvenance ||
		FrozenMaterializationPolicy().MaxThriftRWClients != MaxThriftRWClients {
		t.Fatalf("thriftrw provenance identity = %q / %q", ThriftRWProvenance, PackVersion)
	}
	view := buildYARPCCatalog(t, yarpcFixture{})
	byMethod := make(map[string]gocaller.DirectDescriptor)
	for _, descriptor := range view.Descriptors() {
		byMethod[descriptor.Method] = descriptor
	}
	for method, operation := range map[string]string{
		"Echo": "/echo.Echo/echo", "PingTwice": "/echo.Echo/ping_twice",
	} {
		got := byMethod[method]
		if got.State != StateResolved || got.Operation != operation ||
			got.ClientType != "Interface" || got.DeclarationPath != yarpcIDLPath ||
			got.DeclarationLineage != yarpcLineage || got.ImportPath != "example.test/thrift/echo/echoclient" {
			t.Fatalf("%s descriptor = %+v, want resolved %s", method, got, operation)
		}
	}
	calls, unresolved := scanYARPCCaller(t, view)
	if want := []string{"/echo.Echo/echo", "/echo.Echo/ping_twice"}; !slices.Equal(calls, want) || len(unresolved) != 0 {
		t.Fatalf("YARPC calls = %v (unresolved %v), want %v", calls, unresolved, want)
	}
}

// TestThriftRWProvenanceAbstains covers every relation the rule refuses: the
// calls stay explicit abstentions and carry no declaration authority.
func TestThriftRWProvenanceAbstains(t *testing.T) {
	for _, test := range []struct {
		name    string
		fixture yarpcFixture
		reason  string
		state   string
	}{
		{name: "hash mismatch", fixture: yarpcFixture{moduleSHA1: strings.Repeat("0", 40)},
			state: StateUnavailable, reason: "thriftrw_declaration_hash_mismatch"},
		{name: "two declared files match", fixture: yarpcFixture{extraIDLPath: "vendor-idl/echo.thrift"},
			state: StateAmbiguous, reason: "thriftrw_declaration_ambiguous"},
	} {
		t.Run(test.name, func(t *testing.T) {
			view := buildYARPCCatalog(t, test.fixture)
			descriptors := view.Descriptors()
			if len(descriptors) == 0 {
				t.Fatal("abstaining client emitted no descriptors; its calls would be silently absent")
			}
			for _, descriptor := range descriptors {
				if descriptor.State != test.state || descriptor.Reason != test.reason ||
					descriptor.DeclarationLineage != "" || descriptor.DeclarationPath != "" {
					t.Fatalf("%s descriptor = %+v, want %s/%s", descriptor.Method, descriptor, test.state, test.reason)
				}
			}
			calls, unresolved := scanYARPCCaller(t, view)
			if len(calls) != 0 || len(unresolved) != 2 {
				t.Fatalf("calls %v unresolved %v; want two abstentions", calls, unresolved)
			}
		})
	}
}

// TestThriftRWProvenanceWithoutModuleDescribesNothing: when no thriftrw module
// declares the helper package, the Thrift method spellings are unknown, so the
// client is not described (its audit row records thriftrw_module_missing) and
// its calls are neither resolved nor attached to an invented operation.
func TestThriftRWProvenanceWithoutModuleDescribesNothing(t *testing.T) {
	view := buildYARPCCatalog(t, yarpcFixture{modulePackage: "example.test/other/echo"})
	if descriptors := view.Descriptors(); len(descriptors) != 0 {
		t.Fatalf("client without a module was described: %+v", descriptors)
	}
	if calls, unresolved := scanYARPCCaller(t, view); len(calls) != 0 || len(unresolved) != 0 {
		t.Fatalf("calls %v unresolved %v; want none", calls, unresolved)
	}
}

// TestThriftRWProvenanceDefersToExplicitMapping keeps an explicit
// generated-from mapping authoritative: the derived pass skips the file, and
// the Apache describer the mapping selects finds no YARPC symbols.
func TestThriftRWProvenanceDefersToExplicitMapping(t *testing.T) {
	view := buildYARPCCatalog(t, yarpcFixture{snapshot: true})
	for _, descriptor := range view.Descriptors() {
		if descriptor.ClientType == "Interface" {
			t.Fatalf("derived provenance overrode an explicit mapping: %+v", descriptor)
		}
	}
}
